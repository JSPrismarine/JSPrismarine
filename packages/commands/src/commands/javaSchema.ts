const INVALID: (reader: StringReader, message: string) => never = (reader, message) => {
    throw CommandSyntaxException.BUILT_IN_EXCEPTIONS.dispatcherParseException().createWithContext(reader, message);
};
const EMPTY_PARSE_CONTEXT = { getSource: () => undefined };

const readStructuredToken = (reader: StringReader): string => {
    const start = reader.getCursor();
    let squareDepth = 0;
    let braceDepth = 0;
    let parenDepth = 0;
    let quote = '';
    let escaped = false;

    while (reader.canRead()) {
        const character = reader.peek();
        if (quote.length > 0) {
            reader.skip();
            if (escaped) escaped = false;
            else if (character === '\\') escaped = true;
            else if (character === quote) quote = '';
            continue;
        }

        if (/\s/.test(character) && squareDepth === 0 && braceDepth === 0 && parenDepth === 0) break;
        reader.skip();
        if (character === '"' || character === "'") quote = character;
        else if (character === '[') squareDepth += 1;
        else if (character === ']') squareDepth -= 1;
        else if (character === '{') braceDepth += 1;
        else if (character === '}') braceDepth -= 1;
        else if (character === '(') parenDepth += 1;
        else if (character === ')') parenDepth -= 1;
    }

    const token = reader.getString().slice(start, reader.getCursor());
    if (token.length === 0 || squareDepth < 0 || braceDepth < 0 || parenDepth < 0 || quote.length > 0) {
        INVALID(reader, 'Expected a complete command argument');
    }
    return token;
};

const customType = <T>(gap: string, parse: (reader: StringReader) => T): BedrockDescribedType<T> => ({
    parse: (reader) => parse(reader),
    describeBedrock: () => undefined,
    bedrockGap: gap
});

const readNumberRange = (reader: StringReader, integer: boolean): IntegerRange => {
    const token = reader.readUnquotedString();
    const split = token.indexOf('..');
    const read = (value: string): number => {
        const number = Number(value);
        if (!Number.isFinite(number) || (integer && !Number.isInteger(number))) {
            INVALID(reader, `'${value}' is not a valid ${integer ? 'integer' : 'number'} range`);
        }
        return number;
    };

    if (split < 0) {
        const value = read(token);
        return { min: value, max: value };
    }

    const min = token.slice(0, split);
    const max = token.slice(split + 2);
    if (min.length === 0 && max.length === 0) INVALID(reader, 'A range needs at least one bound');
    return {
        ...(min.length > 0 ? { min: read(min) } : {}),
        ...(max.length > 0 ? { max: read(max) } : {})
    };
};

const registryValues = (registry: string, commands: CommandRegistry<CommandSource>): readonly string[] | undefined => {
    const content = commands.getContent();
    if (registry === 'minecraft:block') return content.blocks;
    if (registry === 'minecraft:item') return content.items;
    if (registry === 'minecraft:entity_type') return content.entityTypes;
    if (registry === 'minecraft:enchantment') return content.enchantments;
    return undefined;
};

const readResourceWithSuffix = (reader: StringReader, registry: string, commands: CommandRegistry<CommandSource>) => {
    const token = readStructuredToken(reader);
    const stateStart = token.indexOf('[');
    const componentStart = token.indexOf('{');
    const suffixStart =
        stateStart < 0 ? componentStart : componentStart < 0 ? stateStart : Math.min(stateStart, componentStart);
    const resourceId = suffixStart < 0 ? token : token.slice(0, suffixStart);
    const resourceReader = new StringReader(resourceId);
    const resource = resourceArgument(registry, registryValues(registry, commands)).parse(
        resourceReader,
        EMPTY_PARSE_CONTEXT
    );
    const suffix = suffixStart < 0 ? '' : token.slice(suffixStart);
    return `${resource}${suffix}`;
};

const javaArgumentType = (
    parser: string,
    properties: Readonly<Record<string, unknown>>,
    commands: CommandRegistry<CommandSource>
): ArgumentType<unknown> => {
    const numberProperty = (name: string): number | undefined => {
        const property = properties[name];
        return typeof property === 'number' ? property : undefined;
    };
    const stringProperty = (name: string): string | undefined => {
        const property = properties[name];
        return typeof property === 'string' ? property : undefined;
    };

    switch (parser) {
        case 'brigadier:bool':
            return BoolArgumentType.bool();
        case 'brigadier:double':
            return customType('Java double arguments are not a Bedrock parameter type', (reader) => {
                const value = Number(reader.readUnquotedString());
                if (!Number.isFinite(value)) INVALID(reader, 'Expected a number');
                return value;
            });
        case 'brigadier:float':
            return FloatArgumentType.float(numberProperty('min') ?? -Infinity, numberProperty('max') ?? Infinity);
        case 'brigadier:integer':
            return IntegerArgumentType.integer(numberProperty('min') ?? -Infinity, numberProperty('max') ?? Infinity);
        case 'brigadier:string': {
            const type = stringProperty('type');
            if (type === 'greedy') return StringArgumentType.greedyString();
            if (type === 'phrase') return StringArgumentType.string();
            return StringArgumentType.word();
        }
        case 'minecraft:entity':
        case 'minecraft:game_profile':
            return entityArgument();
        case 'minecraft:score_holder':
            return scoreHolderArgument();
        case 'minecraft:vec3':
            return positionArgument();
        case 'minecraft:block_pos':
            return blockPositionArgument();
        case 'minecraft:vec2':
            return customType('Java two-dimensional positions are not a Bedrock parameter type', (reader) => {
                const x = relativeValueArgument().parse(reader, EMPTY_PARSE_CONTEXT);
                reader.skipWhitespace();
                const z = relativeValueArgument().parse(reader, EMPTY_PARSE_CONTEXT);
                return [x, z] as const;
            });
        case 'minecraft:rotation':
            return customType('Java rotations are not a Bedrock parameter type', (reader) => {
                const yaw = relativeValueArgument().parse(reader, EMPTY_PARSE_CONTEXT);
                reader.skipWhitespace();
                const pitch = relativeValueArgument().parse(reader, EMPTY_PARSE_CONTEXT);
                return [yaw, pitch] as const;
            });
        case 'minecraft:float_range':
            return customType('Java float ranges are not a Bedrock parameter type', (reader) =>
                readNumberRange(reader, false)
            );
        case 'minecraft:int_range':
            return integerRangeArgument();
        case 'minecraft:time':
            return timeArgument(numberProperty('min') === undefined ? {} : { min: numberProperty('min') });
        case 'minecraft:entity_anchor':
            return anchorArgument();
        case 'minecraft:dimension':
            return stringArgument();
        case 'minecraft:gamemode':
            return enumArgument('GameMode', ['survival', 'creative', 'adventure', 'spectator'] as const);
        case 'minecraft:swizzle':
            return enumArgument('Swizzle', [
                'x',
                'y',
                'z',
                'xy',
                'xz',
                'yx',
                'yz',
                'zx',
                'zy',
                'xyz',
                'xzy',
                'yxz',
                'yzx',
                'zxy',
                'zyx'
            ] as const);
        case 'minecraft:operation':
            return operationArgument();
        case 'minecraft:item_stack':
            return {
                ...resourceArgument('minecraft:item', registryValues('minecraft:item', commands)),
                parse: (reader) => readResourceWithSuffix(reader, 'minecraft:item', commands),
                bedrockGap: 'Java item components are not a Bedrock parameter type'
            };
        case 'minecraft:block_state':
            return {
                ...resourceArgument('minecraft:block', registryValues('minecraft:block', commands)),
                parse: (reader) => readResourceWithSuffix(reader, 'minecraft:block', commands),
                bedrockGap: 'Java block states are not a Bedrock parameter type'
            };
        case 'minecraft:block_predicate':
        case 'minecraft:item_predicate':
        case 'minecraft:slot_source':
        case 'minecraft:item_slot':
        case 'minecraft:objective':
        case 'minecraft:objective_criteria':
        case 'minecraft:scoreboard_slot':
        case 'minecraft:style':
        case 'minecraft:heightmap':
        case 'minecraft:feature':
        case 'minecraft:context_float_provider':
        case 'minecraft:context_int_provider':
        case 'minecraft:resource_location':
            return stringArgument();
        case 'minecraft:resource':
        case 'minecraft:resource_key': {
            const registry = stringProperty('registry') ?? 'minecraft:unknown';
            return resourceArgument(registry, registryValues(registry, commands));
        }
        case 'minecraft:resource_or_tag':
        case 'minecraft:resource_or_tag_key':
            return customType('Java resource tags are not a Bedrock parameter type', (reader) =>
                readStructuredToken(reader)
            );
        case 'minecraft:function':
            return filePathArgument();
        case 'minecraft:loot_modifier':
            return itemModifierArgument();
        case 'minecraft:loot_predicate':
            return lootPredicateArgument();
        case 'minecraft:loot_table':
            return lootTableArgument();
        case 'minecraft:message':
            return messageArgument();
        case 'minecraft:component':
            return jsonArgument();
        case 'minecraft:nbt_path':
            return nbtPathArgument();
        case 'minecraft:nbt_tag':
            return nbtTagArgument();
        case 'minecraft:nbt_compound_tag':
            return nbtCompoundArgument();
        case 'minecraft:particle':
            return resourceArgument('minecraft:particle_type');
        case 'minecraft:template_mirror':
            return enumArgument('TemplateMirror', ['none', 'front_back', 'left_right'] as const);
        case 'minecraft:template_rotation':
            return enumArgument('TemplateRotation', [
                'none',
                'clockwise_90',
                'clockwise_180',
                'counterclockwise_90'
            ] as const);
        default:
            return customType(`No Bedrock parameter maps to Java parser ${parser}`, (reader) =>
                readStructuredToken(reader)
            );
    }
};

const legacyParts = (root: LiteralCommandNode<CommandSource>): LegacyExecutor[] => {
    const executors: LegacyExecutor[] = [];
    const visit = (node: CommandNode<CommandSource>, parts: readonly LegacyPathPart[]): void => {
        const execute = node.getCommand();
        if (execute !== null) executors.push({ parts, execute });

        for (const child of node.getChildren()) {
            if (child instanceof LiteralCommandNode) {
                visit(child, [...parts, { kind: 'literal', name: child.getLiteral() }]);
            } else if (child instanceof ArgumentCommandNode) {
                visit(child, [...parts, { kind: 'argument', name: child.getName(), node: child }]);
            }
        }
    };

    if (root.getCommand() !== null) executors.push({ parts: [], execute: root.getCommand()! });
    for (const child of root.getChildren()) {
        if (child instanceof LiteralCommandNode) visit(child, [{ kind: 'literal', name: child.getLiteral() }]);
        else if (child instanceof ArgumentCommandNode)
            visit(child, [{ kind: 'argument', name: child.getName(), node: child }]);
    }
    return executors;
};

const javaBedrockType = (part: JavaPathPart): string | undefined => {
    switch (part.parser) {
        case 'brigadier:integer':
            return 'INT';
        case 'brigadier:float':
        case 'brigadier:double':
            return 'VAL';
        case 'brigadier:bool':
            return 'BOOL';
        case 'brigadier:string':
            return part.properties?.type === 'greedy' ? 'MESSAGE_ROOT' : 'ID';
        case 'minecraft:entity':
        case 'minecraft:game_profile':
            return 'SELECTION';
        case 'minecraft:vec3':
            return 'POSITION_FLOAT';
        case 'minecraft:block_pos':
            return 'POSITION';
        case 'minecraft:time':
            return 'INT';
        case 'minecraft:message':
            return 'MESSAGE_ROOT';
        case 'minecraft:operation':
            return 'OPERATOR';
        default:
            return undefined;
    }
};

const legacyArgumentShape = (part: LegacyPathPart): string | undefined => {
    if (part.kind !== 'argument' || part.node === undefined) return undefined;
    const type = part.node.getType();
    if (!describesBedrock(type)) return undefined;
    const shape = type.describeBedrock();
    return shape?.kind === 'basic' ? shape.type : shape?.kind === 'enum' ? `ENUM:${shape.values.join('|')}` : undefined;
};

const compatibleArgument = (legacy: LegacyPathPart, java: JavaPathPart): number => {
    const shape = legacyArgumentShape(legacy);
    if (shape === undefined) return 0;
    const javaShape = javaBedrockType(java);
    if (javaShape === undefined) return 0;
    if (
        (shape === 'POSITION' || shape === 'POSITION_FLOAT') &&
        (javaShape === 'POSITION' || javaShape === 'POSITION_FLOAT')
    ) {
        return 4;
    }
    if (shape === javaShape || shape === 'ID' || (shape.startsWith('ENUM:') && javaShape === 'BOOL')) return 4;
    return -8;
};

const literalValues = (part: LegacyPathPart): readonly string[] => {
    const shape = legacyArgumentShape(part);
    return shape?.startsWith('ENUM:') ? shape.slice('ENUM:'.length).split('|') : [];
};

const bindLegacyArguments = (
    legacy: LegacyExecutor,
    javaPath: readonly JavaPathPart[],
    shiftAfterLiteral = false,
    bindRecipeWildcard = false
): Map<string, ArgumentBinding> | undefined => {
    const legacyArgs = legacy.parts.filter((part) => part.kind === 'argument');
    const javaArgs = javaPath.filter((part) => part.kind === 'argument');
    const bindings = new Map<string, ArgumentBinding>();
    let literalBindings = 0;

    for (let index = 0; index < legacyArgs.length; index += 1) {
        const legacyArgument = legacyArgs[index];
        if (legacyArgument === undefined) continue;

        const exact = javaArgs.find((part) => part.name.toLowerCase() === legacyArgument.name.toLowerCase());
        if (exact !== undefined) {
            if (compatibleArgument(legacyArgument, exact) < 0) return undefined;
            bindings.set(legacyArgument.name, { kind: 'argument', name: exact.name });
            continue;
        }

        const enumLiteral = javaPath.find(
            (part) =>
                part.kind === 'literal' &&
                (literalValues(legacyArgument).includes(part.name) ||
                    (bindRecipeWildcard && legacyArgument.name === 'recipe' && part.name === '*'))
        );
        if (enumLiteral !== undefined) {
            bindings.set(legacyArgument.name, { kind: 'literal', value: enumLiteral.name });
            if (shiftAfterLiteral) literalBindings += 1;
            continue;
        }

        const positional = javaArgs[index - literalBindings];
        if (positional !== undefined && compatibleArgument(legacyArgument, positional) >= 0) {
            bindings.set(legacyArgument.name, { kind: 'argument', name: positional.name });
            continue;
        }

        return undefined;
    }

    const boundJavaArguments = new Set(
        [...bindings.values()].flatMap((binding) => (binding.kind === 'argument' ? [binding.name] : []))
    );
    if (javaArgs.some((part) => !boundJavaArguments.has(part.name))) return undefined;

    const boundLiterals = new Set(
        [...bindings.values()].flatMap((binding) => (binding.kind === 'literal' ? [binding.value] : []))
    );
    if (
        javaPath.some(
            (part) =>
                part.kind === 'literal' &&
                !legacy.parts.some((legacyPart) => legacyPart.kind === 'literal' && legacyPart.name === part.name) &&
                !boundLiterals.has(part.name)
        )
    )
        return undefined;

    return bindings;
};

const scoreLegacyExecutor = (
    legacy: LegacyExecutor,
    javaPath: readonly JavaPathPart[],
    shiftAfterLiteral = false,
    bindRecipeWildcard = false
): number => {
    const bindings = bindLegacyArguments(legacy, javaPath, shiftAfterLiteral, bindRecipeWildcard);
    if (bindings === undefined) return Number.NEGATIVE_INFINITY;
    if (legacy.parts.length === 0 && javaPath.length === 0) return 10;
    let score = bindings.size * 4 - Math.abs(legacy.parts.length - javaPath.length);

    for (const part of legacy.parts) {
        if (part.kind === 'literal') {
            if (javaPath.some((candidate) => candidate.kind === 'literal' && candidate.name === part.name)) score += 10;
            else score -= 8;
        } else if (javaPath.some((candidate) => candidate.kind === 'argument' && candidate.name === part.name)) {
            score += 6;
        }
    }

    return score;
};

const mappedContext = (
    context: CommandContext<CommandSource>,
    legacy: LegacyExecutor,
    javaPath: readonly JavaPathPart[],
    shiftAfterLiteral = false,
    bindRecipeWildcard = false
): CommandContext<CommandSource> => {
    const bindings =
        bindLegacyArguments(legacy, javaPath, shiftAfterLiteral, bindRecipeWildcard) ??
        new Map<string, ArgumentBinding>();
    return new Proxy(context, {
        get(target, property) {
            if (property === 'getArgument') {
                return (name: string, clazz?: Function) => {
                    const binding = bindings.get(name);
                    if (binding === undefined) return target.getArgument(name, clazz);
                    let result: unknown =
                        binding.kind === 'literal' ? binding.value : target.getArgument(binding.name, clazz);
                    if (
                        typeof result === 'boolean' &&
                        legacy.parts.some(
                            (part) =>
                                part.kind === 'argument' &&
                                part.name === name &&
                                literalValues(part).includes(String(result))
                        )
                    ) {
                        result = String(result);
                    }
                    return binding.kind === 'literal' && clazz !== undefined ? clazz(result) : result;
                };
            }
            const member = Reflect.get(target, property, target);
            return typeof member === 'function' ? member.bind(target) : member;
        }
    });
};

const routeName = (path: readonly JavaPathPart[]): string =>
    path.map((part) => (part.kind === 'literal' ? part.name : `<${part.name}>`)).join(' ');

const findLegacyExecutor = (
    commandName: string,
    path: readonly JavaPathPart[],
    executors: readonly LegacyExecutor[]
): CommandExecutor | undefined => {
    if (commandName === 'teleport') return teleportExecutor(path);
    if (commandName === 'gamerule') return gameRuleExecutor(path);
    const shiftAfterLiteral = commandName === 'title';
    const bindRecipeWildcard = commandName === 'recipe';

    const ranked = executors
        .map((executor) => ({
            executor,
            score: scoreLegacyExecutor(executor, path, shiftAfterLiteral, bindRecipeWildcard)
        }))
        .filter((entry) => Number.isFinite(entry.score))
        .sort((left, right) => right.score - left.score);
    const best = ranked[0];
    if (best === undefined || best.score < 3) return undefined;
    return (context) =>
        best.executor.execute(mappedContext(context, best.executor, path, shiftAfterLiteral, bindRecipeWildcard));
};

const faceRotation = (origin: Vector3, destination: Vector3): Rotation => {
    const x = destination.x - origin.x;
    const y = destination.y - origin.y;
    const z = destination.z - origin.z;
    const horizontal = Math.hypot(x, z);
    return { yaw: (Math.atan2(-x, z) * 180) / Math.PI, pitch: (-Math.atan2(y, horizontal) * 180) / Math.PI };
};

const teleportExecutor = (path: readonly JavaPathPart[]): CommandExecutor | undefined => {
    const route = path.map((part) => `${part.kind}:${part.name}`);

    if (route.join(' ') === 'argument:destination') {
        return command((context) => {
            const current = source(context);
            if (current.entity === undefined) return report(current, 0, 'No entity to teleport');
            const destination = selectOne(current, value(context, 'destination'));
            const moved = current.host.entities.teleport(
                current.entity,
                destination.position,
                destination.rotation,
                destination.dimension
            );
            return report(current, moved ? 1 : 0, `Teleported to ${destination.name}`);
        });
    }

    if (route.join(' ') === 'argument:location') {
        return command((context) => {
            const current = source(context);
            if (current.entity === undefined) return report(current, 0, 'No entity to teleport');
            const position = resolvePosition(value<CoordinateTriple>(context, 'location'), current);
            const moved = current.host.entities.teleport(
                current.entity,
                position,
                current.entity.rotation,
                current.dimension
            );
            return report(current, moved ? 1 : 0, `Teleported to ${current.entity.name}`);
        });
    }

    if (route.join(' ') === 'argument:targets argument:destination') {
        return command((context) => {
            const current = source(context);
            const destination = selectOne(current, value(context, 'destination'));
            const moved = select(current, value(context, 'targets')).filter((entity) =>
                current.host.entities.teleport(
                    entity,
                    destination.position,
                    destination.rotation,
                    destination.dimension
                )
            ).length;
            return report(current, moved, `Teleported ${moved} entities to ${destination.name}`);
        });
    }

    if (route.join(' ') === 'argument:targets argument:location argument:rotation') {
        return command((context) => {
            const current = source(context);
            const position = resolvePosition(value<CoordinateTriple>(context, 'location'), current);
            const coordinates = value<readonly [Coordinate, Coordinate]>(context, 'rotation');
            const rotation = resolveRotation(coordinates[0], coordinates[1], current);
            const moved = select(current, value(context, 'targets')).filter((entity) =>
                current.host.entities.teleport(entity, position, rotation, current.dimension)
            ).length;
            return report(current, moved, `Teleported ${moved} entities`);
        });
    }

    if (route.join(' ') === 'argument:targets argument:location literal:facing argument:facingLocation') {
        return command((context) => {
            const current = source(context);
            const position = resolvePosition(value<CoordinateTriple>(context, 'location'), current);
            const facing = resolvePosition(value<CoordinateTriple>(context, 'facingLocation'), current);
            const rotation = faceRotation(position, facing);
            const moved = select(current, value(context, 'targets')).filter((entity) =>
                current.host.entities.teleport(entity, position, rotation, current.dimension)
            ).length;
            return report(current, moved, `Teleported ${moved} entities`);
        });
    }

    if (
        route.join(' ') ===
        'argument:targets argument:location literal:facing literal:entity argument:facingEntity argument:facingAnchor'
    ) {
        return command((context) => {
            const current = source(context);
            const position = resolvePosition(value<CoordinateTriple>(context, 'location'), current);
            const target = selectOne(current, value(context, 'facingEntity'));
            const anchor = value<'eyes' | 'feet'>(context, 'facingAnchor');
            const eyeOffset = anchor === 'eyes' && target.isPlayer ? 1.62 : 0;
            const facing = { ...target.position, y: target.position.y + eyeOffset };
            const rotation = faceRotation(position, facing);
            const moved = select(current, value(context, 'targets')).filter((entity) =>
                current.host.entities.teleport(entity, position, rotation, current.dimension)
            ).length;
            return report(current, moved, `Teleported ${moved} entities`);
        });
    }

    return undefined;
};

const gameRuleExecutor = (path: readonly JavaPathPart[]): CommandExecutor | undefined => {
    const [rulePart] = path;
    if (rulePart?.kind !== 'literal') return undefined;
    const rule = gameRule(rulePart.name);
    if (rule === undefined) return undefined;
    const ruleName = rule.name;
    const writes = path.some((part) => part.kind === 'argument' && part.name === 'value');

    return command((context) => {
        const current = source(context);
        if (!writes) {
            const existing = current.host.world.getGameRule(ruleName);
            current.sendFeedback(`${ruleName} = ${String(existing)}`);
            return typeof existing === 'number' ? existing : existing === true ? 1 : 0;
        }

        const raw = value<string | number | boolean>(context, 'value');
        const changed = current.host.world.setGameRule(ruleName, raw);
        return report(current, changed ? 1 : 0, `${ruleName} = ${String(raw)}`);
    });
};

const dataPathPart = (name: string, data: JavaCommandNodeData): JavaPathPart =>
    data.type === 'literal'
        ? { kind: 'literal', name }
        : {
              kind: 'argument',
              name,
              ...(data.parser === undefined ? {} : { parser: data.parser }),
              ...(data.properties === undefined ? {} : { properties: data.properties })
          };

const buildDataNode = (
    name: string,
    data: JavaCommandNodeData,
    path: readonly JavaPathPart[],
    commandName: string,
    executors: readonly LegacyExecutor[],
    registry: CommandRegistry<CommandSource>
): CommandNode<CommandSource> => {
    const part = dataPathPart(name, data);
    const nextPath = [...path, part];
    const executor = data.executable === true ? findLegacyExecutor(commandName, nextPath, executors) : undefined;
    const fallback =
        data.executable === true && executor === undefined
            ? command((context) => {
                  const current = source(context);
                  current.sendError(
                      `The Java form '/${commandName} ${routeName(nextPath)}' has no host implementation.`
                  );
                  return 0;
              })
            : undefined;
    const run = executor ?? fallback;
    const redirect = data.redirect === undefined ? undefined : resolveRedirect(data.redirect, registry);
    const children = Object.entries(data.children ?? {});

    if (data.type === 'literal') {
        const builder = literal<CommandSource>(name);
        if (redirect !== undefined) builder.redirect(redirect);
        else
            for (const [childName, child] of children)
                builder.then(buildDataNode(childName, child, nextPath, commandName, executors, registry));
        if (run !== undefined) builder.executes(run);
        return builder.build();
    }

    if (data.type !== 'argument' || data.parser === undefined) {
        throw new Error(`Java command node '${name}' has no argument parser.`);
    }
    const builder = argument<CommandSource, unknown>(
        name,
        javaArgumentType(data.parser, data.properties ?? {}, registry)
    );
    if (redirect !== undefined) builder.redirect(redirect);
    else
        for (const [childName, child] of children)
            builder.then(buildDataNode(childName, child, nextPath, commandName, executors, registry));
    if (run !== undefined) builder.executes(run);
    return builder.build();
};

const resolveRedirect = (
    path: readonly string[],
    registry: CommandRegistry<CommandSource>
): CommandNode<CommandSource> => {
    let target: CommandNode<CommandSource> = registry.getRoot();
    for (const part of path) {
        const child = target.getChild(part);
        if (child === undefined) throw new Error(`Java command redirect '${path.join(' ')}' is not registered.`);
        target = child;
    }
    return target;
};

const mergeArgumentTypes = (existing: CommandNode<CommandSource>, incoming: CommandNode<CommandSource>): void => {
    if (existing instanceof ArgumentCommandNode && incoming instanceof ArgumentCommandNode) {
        existing.setType(incoming.getType());
    }

    for (const incomingChild of incoming.getChildren()) {
        const existingChild = existing.getChild(incomingChild.getName());
        if (existingChild !== undefined) mergeArgumentTypes(existingChild, incomingChild);
    }
};

const mergeJavaNode = (parent: CommandNode<CommandSource>, incoming: CommandNode<CommandSource>): void => {
    const existing = parent.getChild(incoming.getName());
    if (existing !== undefined) mergeArgumentTypes(existing, incoming);
    parent.addChild(incoming);
};

/** Adds Java 26.3 command routes for the command names this server implements. */
export const extendWithJavaCommandData = (registry: CommandRegistry<CommandSource>, names: readonly string[]): void => {
    for (const commandName of names) {
        const javaName = DATA_COMMAND_NAMES[commandName] ?? commandName;
        const dataRoot = javaCommandTree.children[javaName];
        const commandRoot = registry.getRoot().getChild(commandName);
        if (dataRoot === undefined || !(commandRoot instanceof LiteralCommandNode)) continue;

        const executors = legacyParts(commandRoot);
        for (const [name, node] of Object.entries(dataRoot.children ?? {})) {
            mergeJavaNode(commandRoot, buildDataNode(name, node, [], commandName, executors, registry));
        }
    }
};
