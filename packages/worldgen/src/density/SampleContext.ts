import type { DensitySampler } from './compile';

class CacheCell {
    public x = 0;
    public y = 0;
    public z = 0;
    public valid = false;
    public value = 0;
}

/**
 * The per-chunk state a compiled density function tree reads while sampling.
 *
 * Java keeps the same split: the function tree is immutable and shared across chunks and
 * threads, and everything mutable or chunk-specific lives here. The three overrides are the
 * seams the world blender and the structure beard hook into.
 */
export class SampleContext {
    /**
     * Replaces `blend_alpha`, which is 1 outside a blending region. The world blender sets it
     * when a chunk borders terrain generated by an older version.
     */
    public blendAlpha: DensitySampler | undefined;
    /** Replaces `blend_offset`, which is 0 outside a blending region. */
    public blendOffset: DensitySampler | undefined;
    /** Replaces `beardifier`, which is 0 where no structure pushes terrain around. */
    public beardifier: DensitySampler | undefined;
    /** Post-processes `blend_density`, which is the identity outside a blending region. */
    public blendDensity: ((x: number, y: number, z: number, density: number) => number) | undefined;

    private readonly cells: CacheCell[] = [];

    /** Returns the memo slot a compiled `cache` node owns, creating it on first use. */
    public cell(id: number): CacheCell {
        const existing = this.cells[id];
        if (existing) return existing;
        const created = new CacheCell();
        this.cells[id] = created;
        return created;
    }

    /** Drops every memoized value, which a caller does when it moves to another chunk. */
    public reset(): void {
        for (const cell of this.cells) cell.valid = false;
    }
}
