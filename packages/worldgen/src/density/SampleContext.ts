import type { DensitySampler } from './compile';

class CacheCell {
    public x = 0;
    public y = 0;
    public z = 0;
    public valid = false;
    public value = 0;
}

/** How many cells of the corner lattice a {@link CornerCache} indexes across x and across z. */
const CORNER_CACHE_CELLS_XZ = 16;

/** How many cells of the corner lattice a {@link CornerCache} indexes up the y axis. */
const CORNER_CACHE_CELLS_Y = 64;

/** The number of slots a {@link CornerCache} holds. */
const CORNER_CACHE_SLOTS = CORNER_CACHE_CELLS_XZ * CORNER_CACHE_CELLS_XZ * CORNER_CACHE_CELLS_Y;

/**
 * The cell-corner values an `interpolated` function has already computed.
 *
 * Corners sit on a regular lattice, so the slot is the cell index masked per axis rather than a
 * hash of the position. A chunk's lattice is 5 by 5 cells across and 48 up, which lands inside
 * one window of the 16 by 16 by 64 the masks carve out, so no two corners a chunk is working on
 * can collide. A hashed index collided often enough to compute a chunk's 1225 corners 6139
 * times, and a corner is the most expensive thing the density stack does.
 *
 * The cache is still direct-mapped, so a position outside that window evicts rather than grows,
 * and the stored cell indices are compared exactly before a value is reused. Eviction costs a
 * recomputation, never an answer, because a density function tree is deterministic for one
 * context. Java fills a whole cell grid up front; this covers the same working set without
 * having to visit the chunk in Java's cell order.
 */
export class CornerCache {
    private readonly keyX = new Int32Array(CORNER_CACHE_SLOTS);
    private readonly keyY = new Int32Array(CORNER_CACHE_SLOTS);
    private readonly keyZ = new Int32Array(CORNER_CACHE_SLOTS);
    private readonly filled = new Uint8Array(CORNER_CACHE_SLOTS);
    private readonly values = new Float64Array(CORNER_CACHE_SLOTS);

    /**
     * Returns the corner value, computing it through `input` when the slot does not hold it.
     *
     * @param cellX - The corner's lattice index across x, which is `x / cellSizeXz`. The caller
     *   already has it, and passing it keeps the division out of this path.
     */
    public getOrCompute(
        context: SampleContext,
        input: DensitySampler,
        cellX: number,
        cellY: number,
        cellZ: number,
        x: number,
        y: number,
        z: number
    ): number {
        const slot =
            (cellX & (CORNER_CACHE_CELLS_XZ - 1)) |
            ((cellZ & (CORNER_CACHE_CELLS_XZ - 1)) << 4) |
            ((cellY & (CORNER_CACHE_CELLS_Y - 1)) << 8);
        if (
            this.filled[slot] === 1 &&
            this.keyX[slot] === cellX &&
            this.keyY[slot] === cellY &&
            this.keyZ[slot] === cellZ
        ) {
            return this.values[slot] ?? 0;
        }

        const value = input(context, x, y, z);
        this.keyX[slot] = cellX;
        this.keyY[slot] = cellY;
        this.keyZ[slot] = cellZ;
        this.values[slot] = value;
        this.filled[slot] = 1;
        return value;
    }

    /** Drops every memoized corner. */
    public clear(): void {
        this.filled.fill(0);
    }
}

/**
 * The per-chunk state a compiled density function tree reads while sampling.
 *
 * Java keeps the same split: the function tree is immutable and shared across chunks and
 * threads, and everything mutable or chunk-specific lives here. The three overrides are the
 * seams the world blender and the structure beard hook into.
 */
export class SampleContext {
    /**
     * Replaces `blend_alpha`, which is 1 outside a blending region. The world blender sets it
     * when a chunk borders terrain generated by an older version.
     */
    public blendAlpha: DensitySampler | undefined;
    /** Replaces `blend_offset`, which is 0 outside a blending region. */
    public blendOffset: DensitySampler | undefined;
    /** Replaces `beardifier`, which is 0 where no structure pushes terrain around. */
    public beardifier: DensitySampler | undefined;
    /** Post-processes `blend_density`, which is the identity outside a blending region. */
    public blendDensity: ((x: number, y: number, z: number, density: number) => number) | undefined;

    private readonly cells: CacheCell[] = [];
    private readonly cornerCaches: CornerCache[] = [];
    private readonly currentCorners: Float64Array[] = [];
    private readonly currentCellX: number[] = [];
    private readonly currentCellY: number[] = [];
    private readonly currentCellZ: number[] = [];

    /** Returns the memo slot a compiled `cache` node owns, creating it on first use. */
    public cell(id: number): CacheCell {
        const existing = this.cells[id];
        if (existing) return existing;
        const created = new CacheCell();
        this.cells[id] = created;
        return created;
    }

    /** Returns the corner cache a compiled `interpolated` node fills, creating it on first use. */
    public cornerCache(id: number): CornerCache {
        const existing = this.cornerCaches[id];
        if (existing) return existing;
        const created = new CornerCache();
        this.cornerCaches[id] = created;
        return created;
    }

    /** Returns the eight corners of the current interpolation cell, or undefined on a cell change. */
    public interpolationCorners(id: number, x: number, y: number, z: number): Float64Array | undefined {
        return this.currentCellX[id] === x && this.currentCellY[id] === y && this.currentCellZ[id] === z
            ? this.currentCorners[id]
            : undefined;
    }

    /**
     * Marks one interpolation cell current and returns the reusable buffer its eight corners
     * go into, ordered x fastest, then y, then z.
     */
    public beginInterpolationCell(id: number, x: number, y: number, z: number): Float64Array {
        this.currentCellX[id] = x;
        this.currentCellY[id] = y;
        this.currentCellZ[id] = z;
        const existing = this.currentCorners[id];
        if (existing) return existing;
        const created = new Float64Array(8);
        this.currentCorners[id] = created;
        return created;
    }

    /**
     * Drops every memoized value.
     *
     * A caller that walks more than one chunk with one context has to do this between them,
     * or the corner caches keep serving the previous chunk's working set.
     */
    public reset(): void {
        for (const cell of this.cells) cell.valid = false;
        for (const cache of this.cornerCaches) cache.clear();
        this.currentCellX.fill(Number.NaN);
        this.currentCellY.fill(Number.NaN);
        this.currentCellZ.fill(Number.NaN);
    }
}
