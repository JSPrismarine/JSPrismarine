/**
 * Writes `src/tables/vanillaBlockDisplayNames.json` from Bedrock's captured block registry.
 *
 * The source is the `block-types` table the `dump` pass of
 * `pnpm --filter @jsprismarine/bedrock-data run dump:bedrock` writes: one row per block type,
 * with the translation key the Bedrock client localizes as the Script API reports it. It is read
 * for the protocol version `packages/bedrock-data/sources.json` names as the default. The
 * committed table is read by the overlay generator and changes visibly when the capture changes.
 *
 * Run as `pnpm --filter @jsprismarine/blocks run generate:display-names`.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(packageDir, '../..');
const bedrockData = join(repoRoot, 'packages/bedrock-data');
const { defaultProtocolVersion } = JSON.parse(readFileSync(join(bedrockData, 'sources.json'), 'utf8')).bds;
const source = join(bedrockData, `src/jsp/v${defaultProtocolVersion}/bedrock/block-types.json`);
const target = join(packageDir, 'src/tables/vanillaBlockDisplayNames.json');
const { rows } = JSON.parse(readFileSync(source, 'utf8'));
const names = new Map();

for (const row of rows) {
    if (typeof row.id !== 'string' || typeof row.localizationKey !== 'string' || row.localizationKey.length === 0) {
        throw new Error('the Bedrock block capture contains a row without an identifier or translation key');
    }
    if (names.has(row.id)) throw new Error(`${row.id} appears twice in the Bedrock block capture`);
    names.set(row.id, row.localizationKey);
}

const table = {
    $comment: `Generated by utils/generate-display-names.mjs from ${relative(repoRoot, source)}. Do not edit.`,
    blocks: Object.fromEntries([...names].sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0)))
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${JSON.stringify(table, null, 4)}\n`);
console.log(`vanillaBlockDisplayNames: ${names.size} Bedrock block translation keys`);
