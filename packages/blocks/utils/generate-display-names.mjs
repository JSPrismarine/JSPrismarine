/**
 * Writes `src/tables/vanillaBlockDisplayNames.json` from Bedrock's captured block registry.
 *
 * Every row carries the translation key the Bedrock client localizes. Multiple state rows for a
 * block must agree, so a changed capture cannot silently pick one state's name. The committed
 * table is read by the overlay generator and changes visibly when the capture changes.
 *
 * Run as `pnpm --filter @jsprismarine/blocks run generate:display-names`. The package script first
 * ensures the required `@jsprismarine/bedrock-data` resources submodule is initialized.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(packageDir, '../..');
const source = join(repoRoot, 'packages/bedrock-data/src/resources/blocks.json');
const target = join(packageDir, 'src/tables/vanillaBlockDisplayNames.json');
const rows = JSON.parse(readFileSync(source, 'utf8'));
const names = new Map();

for (const row of rows) {
    if (typeof row.name !== 'string' || typeof row.translationKey !== 'string' || row.translationKey.length === 0) {
        throw new Error('the Bedrock block capture contains a row without an identifier or translation key');
    }

    const existing = names.get(row.name);
    if (existing !== undefined && existing !== row.translationKey) {
        throw new Error(`${row.name} has multiple Bedrock translation keys: ${existing}, ${row.translationKey}`);
    }
    names.set(row.name, row.translationKey);
}

const table = {
    $comment:
        'Generated by utils/generate-display-names.mjs from packages/bedrock-data/src/resources/blocks.json. Do not edit.',
    blocks: Object.fromEntries([...names].sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0)))
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${JSON.stringify(table, null, 4)}\n`);
console.log(`vanillaBlockDisplayNames: ${names.size} Bedrock block translation keys`);
