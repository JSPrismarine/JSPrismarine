/**
 * Writes `src/tables/blockLiquidReactions.json` from Bedrock's captured block registry.
 *
 * The source is the `block-types` table the `dump` pass of
 * `pnpm --filter @jsprismarine/bedrock-data run dump:bedrock` writes: each block type's water
 * answers from the Script API, for its default permutation and for every permutation that answers
 * differently. It is read for the protocol version `packages/bedrock-data/sources.json` names as
 * the default. `src/liquidReactions.ts` turns the answers into reactions, and its test checks the
 * committed table against the capture. The script imports it from `dist/` for the reason
 * `generate-overlay.mjs` gives, so the package script builds the package first.
 *
 * Run as `pnpm --filter @jsprismarine/blocks run generate:liquid-reactions`.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { liquidReactionsOf } from '../dist/liquidReactions.js';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(packageDir, '../..');
const bedrockData = join(repoRoot, 'packages/bedrock-data');
const { defaultProtocolVersion } = JSON.parse(readFileSync(join(bedrockData, 'sources.json'), 'utf8')).bds;
const source = join(bedrockData, `src/jsp/v${defaultProtocolVersion}/bedrock/block-types.json`);
const target = join(packageDir, 'src/tables/blockLiquidReactions.json');
const { rows } = JSON.parse(readFileSync(source, 'utf8'));

const blocks = liquidReactionsOf(rows);
const table = {
    $comment: `Generated by utils/generate-liquid-reactions.mjs from ${relative(repoRoot, source)}. Do not edit.`,
    blocks
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${JSON.stringify(table, null, 4)}\n`);

const washed = Object.values(blocks).filter((reaction) => reaction !== 'blocking').length;
console.log(
    `blockLiquidReactions: ${Object.keys(blocks).length} block types, ${washed} that a liquid takes the place of`
);
