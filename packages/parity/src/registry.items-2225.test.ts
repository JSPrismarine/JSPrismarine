import { biome_definitions_network, block_definitions, item_table } from '@jsprismarine/bedrock-data';
import {
    biome_definitions_network as biomes2225,
    block_definitions as blocks2225,
    item_table as item_table_2225
} from '@jsprismarine/bedrock-data/v2225';
import BinaryStream from '@jsprismarine/binaryutils';
import { ByteOrder, NBTReader } from '@jsprismarine/nbt';
import { netIdFor } from '@jsprismarine/protocol/wire/versions/v2193';
import ItemRegistryPacket from '@jsprismarine/protocol/packet/ItemRegistryPacket';
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

import { FAMILIES } from './families.ts';
import { bedrockCaptureAt, loadRequiredItemListAt } from './goldens.ts';
import { reportParityProgress } from './progress.ts';

/**
 * The protocol 2225 tables against the Bedrock Dedicated Server 1.26.60.6 capture they are
 * built from.
 *
 * `registry.items` asks the same question of the default version, 2193. This asks it of the
 * second one, because a per-version table is only worth publishing if it is the version it
 * claims: the way this goes wrong is not a loud failure but a 2225 table silently rebuilt
 * from the 2193 capture, which looks right and puts 82 items on the wrong number.
 *
 * The item registry is server-authoritative - a client adopts the numbering it is sent - so
 * these are not assertions about what a client will accept. They are assertions that what a
 * 2225 session would send is what vanilla 1.26.60 sends.
 */
describe(FAMILIES.registryItems2225, () => {
    const capture = loadRequiredItemListAt(2225);
    const capture2193 = loadRequiredItemListAt(2193);

    it('ships every item of the 1.26.60 capture, on the id and flag the capture recorded', () => {
        const disagreements = Object.entries(capture)
            .filter(([name, entry]) => {
                const ours = item_table_2225[name];
                return (
                    ours === undefined ||
                    ours.runtime_id !== entry.runtime_id ||
                    ours.component_based !== entry.component_based
                );
            })
            .map(([name]) => name);

        expect(disagreements).toEqual([]);
        expect(Object.keys(item_table_2225).sort()).toEqual(Object.keys(capture).sort());
    });

    it('gives every item an Item Version, which the capture does not carry', () => {
        // The column is joined in from that version's CloudburstMC dump, and the join refuses
        // to run when the two disagree. An entry with no version means the join was skipped.
        const missing = Object.entries(item_table_2225)
            .filter(([, entry]) => !Number.isInteger(entry.version))
            .map(([name]) => name);

        expect(missing).toEqual([]);
    });

    it('numbers every item uniquely', () => {
        const ids = Object.values(item_table_2225).map((entry) => entry.runtime_id);

        expect(new Set(ids).size).toBe(ids.length);
    });

    it('is the 1.26.60 table rather than the 1.26.51 one', () => {
        // The failure this family exists for. 2225 adds items 2193 has no name for, and
        // moves items both versions have; either on its own proves the right capture was read.
        const added = Object.keys(capture).filter((name) => !(name in capture2193));
        const moved = Object.keys(capture).filter(
            (name) => name in capture2193 && capture2193[name]!.runtime_id !== capture[name]!.runtime_id
        );

        expect(added.length).toBeGreaterThan(0);
        expect(moved.length).toBeGreaterThan(0);
        for (const name of added) expect(item_table_2225[name]).toBeDefined();
        for (const name of moved) expect(item_table_2225[name]!.runtime_id).toBe(capture[name]!.runtime_id);
    });

    it('drops no item 1.26.51 had', () => {
        expect(Object.keys(capture2193).filter((name) => !(name in item_table_2225))).toEqual([]);
    });

    it('leaves the default version untouched', () => {
        // Both tables are generated by one script from one capture directory each. The 2193
        // table is what every unversioned consumer reads, so it is asserted here too.
        expect(Object.keys(item_table).sort()).toEqual(Object.keys(capture2193).sort());
    });

    it('publishes the block and biome data 1.26.60 did not change, from the 1.26.60 capture', () => {
        // `v2225.ts` documents these as byte-identical to 2193's. That is a measured fact
        // about the release, so it is asserted against the two committed captures rather than
        // assumed, and the exports are then checked to follow their own version's capture. A
        // 1.26.60 that does change one fails here. The block capture's provenance header is
        // excluded from the comparison: it names the server, so it differs by design.
        const definitionsOf = (protocolVersion: number): string =>
            JSON.stringify(
                (
                    JSON.parse(readFileSync(bedrockCaptureAt(protocolVersion, 'block_definitions.json'), 'utf-8')) as {
                        blocks: unknown;
                    }
                ).blocks
            );

        expect(definitionsOf(2225)).toBe(definitionsOf(2193));
        expect(
            readFileSync(bedrockCaptureAt(2225, 'biome_definitions_network.nbt')).equals(
                readFileSync(bedrockCaptureAt(2193, 'biome_definitions_network.nbt'))
            )
        ).toBe(true);

        // And the exports follow the capture of their own version.
        expect(blocks2225).toEqual(block_definitions);
        expect(biomes2225.equals(biome_definitions_network)).toBe(true);
    });

    /**
     * The table is published; this is whether a session speaking 2225 is actually sent it.
     *
     * `ItemRegistryPacket` is what hands a client its numbering, and the codec that stamped
     * the packet picks the table. A 2225 session sent the 2193 table is not a refused join -
     * the registry is authoritative - so nothing else fails loudly when this breaks, which is
     * why it is asserted against the capture rather than against the export.
     */
    describe('what a session is actually sent', () => {
        const sentAt = (protocolVersion: number): Map<string, number> => {
            const packet = new ItemRegistryPacket();
            packet.codecProtocol = protocolVersion;
            packet.encode();

            const stream = new BinaryStream(packet.getBuffer());
            expect(stream.readUnsignedVarInt()).toBe(netIdFor('ItemRegistryPacket'));

            const sent = new Map<string, number>();
            for (let i = 0, count = stream.readUnsignedVarInt(); i < count; i++) {
                const length = stream.readUnsignedVarInt();
                const name = stream.read(length).toString('utf-8');
                const runtimeId = stream.readShortLE();
                stream.readBoolean();
                stream.readVarInt();
                // The positional component compound, read past rather than parsed.
                const reader = new NBTReader(stream, ByteOrder.LITTLE_ENDIAN);
                reader.setUseVarint(true);
                reader.parse();
                sent.set(name, runtimeId);
            }

            expect(stream.feof()).toBe(true);
            return sent;
        };

        it('sends a 2225 session the numbering vanilla 1.26.60 sends', () => {
            const sent = sentAt(2225);

            expect([...sent.keys()].sort()).toEqual(Object.keys(capture).sort());
            for (const [name, entry] of Object.entries(capture)) expect(sent.get(name), name).toBe(entry.runtime_id);
        });

        it('sends a 2193 session the numbering vanilla 1.26.51 sends, unchanged', () => {
            const sent = sentAt(2193);

            expect([...sent.keys()].sort()).toEqual(Object.keys(capture2193).sort());
            for (const [name, entry] of Object.entries(capture2193))
                expect(sent.get(name), name).toBe(entry.runtime_id);
        });

        it('disagrees between the two exactly where the captures disagree', () => {
            const at2193 = sentAt(2193);
            const at2225 = sentAt(2225);

            const moved = [...at2225].filter(([name, id]) => at2193.has(name) && at2193.get(name) !== id);
            const added = [...at2225.keys()].filter((name) => !at2193.has(name));

            expect(moved.map(([name]) => name).sort()).toEqual(
                Object.keys(capture)
                    .filter(
                        (name) => name in capture2193 && capture2193[name]!.runtime_id !== capture[name]!.runtime_id
                    )
                    .sort()
            );
            expect(added.sort()).toEqual(
                Object.keys(capture)
                    .filter((name) => !(name in capture2193))
                    .sort()
            );
        });
    });

    it('reports the current 2225 item catalog volume', () => {
        reportParityProgress(FAMILIES.registryItems2225, {
            capturedItems: Object.keys(capture).length,
            shippedItems: Object.keys(item_table_2225).length,
            addedSince2193: Object.keys(capture).filter((name) => !(name in capture2193)).length,
            renumberedSince2193: Object.keys(capture).filter(
                (name) => name in capture2193 && capture2193[name]!.runtime_id !== capture[name]!.runtime_id
            ).length
        });
    });
});
