/**
 * Runs the chunk generator over the corpus plan and reduces each chunk to what the golden holds.
 *
 * A corpus chunk is still generated alone, in a generator that has produced nothing else, but
 * that is now a choice about cost rather than a constraint. The generator climbs a chunk status
 * ladder, every status is a function of the seed and the chunk position, and a feature's writes
 * across a border are merged in a fixed positional order, so any request order produces the same
 * blocks. `worldgen.determinism` is what holds that; before the ladder it recorded the opposite,
 * and a golden captured under any other protocol would have recorded the generator's history
 * rather than its output.
 *
 * Generating alone is not cheap any more and the sentence has to say so. Asking for one chunk at
 * `full` drives twenty-five terrain tiles and nine feature passes, because the chunk cannot be
 * finished until its eight neighbors have decorated and handed over what they wrote into it.
 *
 * Everything is digested over block state names such as `minecraft:oak_log[pillar_axis=y]`
 * rather than over Bedrock runtime ids. A runtime id is an FNV-1a hash of the serialized state,
 * so adding a property to the block catalog would move every id in the corpus and report a
 * generation change that did not happen.
 */
import { createHash } from 'node:crypto';

import BinaryStream from '@jsprismarine/binaryutils';
import { ByteOrder } from '@jsprismarine/nbt';
import { BlockRuntimeIds } from '@jsprismarine/prismarine/block/state/BlockRuntimeIds';
import type Chunk from '@jsprismarine/prismarine/world/chunk/Chunk';
import { DataDrivenGenerator } from '@jsprismarine/prismarine/world/generators/datadriven/DataDrivenGenerator';
import { findJavaTemplateSource } from '@jsprismarine/prismarine/world/generators/datadriven/javaStructureTemplates';
import type { JavaWorldgenRegistries } from '@jsprismarine/prismarine/world/generators/datadriven/javaWorldgenData';
import {
    cacheRoot,
    findJavaWorldgenSources,
    loadJavaWorldgenRegistries
} from '@jsprismarine/prismarine/world/generators/datadriven/javaWorldgenData';

import type { ChunkDigest, StructurePlacement, WholeChunkSample } from './golden.ts';
import type { CorpusChunk } from './plan.ts';
import { CORPUS_CHUNKS, STRUCTURE_SCAN_RADIUS, STRUCTURE_SCAN_SEEDS } from './plan.ts';

/** The protocol sentence the golden records, so a reader knows how to reproduce it. */
export const CAPTURE_PROTOCOL =
    'Each chunk is generated by a generator that has produced nothing else, which at the full ' +
    'tier drives twenty-five terrain tiles and nine feature passes. Any other order gives the ' +
    'same blocks: every status is a function of the seed and the position, and a feature write ' +
    'across a border is merged in a fixed positional order.';

/** The Java data a capture reads, loaded once and shared by every chunk. */
export interface GenerationEnvironment {
    readonly registries: JavaWorldgenRegistries;
    /** The structure templates, which come out of the Java server jar. */
    readonly templates: ReturnType<typeof findJavaTemplateSource>;
}

/**
 * Loads Java's world generation data, or reports that this checkout does not have it.
 *
 * @returns The registries and templates, or undefined when the fetched datapack or the data
 *   generator reports are missing, which is what makes the corpus rows read "not measured".
 */
export const openGeneration = (): GenerationEnvironment | undefined => {
    const sources = findJavaWorldgenSources();
    if (sources === undefined) return undefined;

    const registries = loadJavaWorldgenRegistries(sources);
    return { registries, templates: findJavaTemplateSource(cacheRoot(), registries.processorLists) };
};

const sha = (parts: Iterable<string>): string => {
    const hash = createHash('sha256');
    for (const part of parts) hash.update(part);
    return hash.digest('hex').slice(0, 32);
};

/** A chunk read out into palette indices, with everything the digests and samples need. */
interface ChunkReading {
    readonly palette: readonly string[];
    /** Palette indices for layer 0, indexed `(x * 16 + z) * height + (y - minY)`. */
    readonly blocks: Uint32Array;
    readonly liquids: Uint32Array;
    /** One biome id per 4 by 4 by 4 cell, indexed `(cellX * 4 + cellZ) * cellsY + cellY`. */
    readonly biomes: Uint16Array;
    readonly heightmap: Uint16Array;
    readonly blockEntities: readonly string[];
    readonly entitySpawns: readonly string[];
    readonly minY: number;
    readonly height: number;
}

/** The name of a runtime id, or a marker naming the id when the catalog cannot resolve it. */
const stateNameOf = (runtimeId: number, names: Map<number, string>): string => {
    const known = names.get(runtimeId);
    if (known !== undefined) return known;

    const resolved = BlockRuntimeIds.getState(runtimeId)?.toString() ?? `unresolved:${runtimeId}`;
    names.set(runtimeId, resolved);
    return resolved;
};

const readChunk = (chunk: Chunk): ChunkReading => {
    const minY = chunk.getMinY();
    // Not `getHeight`, which counts allocated sub chunks rather than blocks.
    const height = chunk.getMaxY() - minY + 1;
    const names = new Map<number, string>();
    const palette: string[] = [];
    const indices = new Map<string, number>();

    const indexOf = (runtimeId: number): number => {
        const name = stateNameOf(runtimeId, names);
        const known = indices.get(name);
        if (known !== undefined) return known;

        indices.set(name, palette.length);
        palette.push(name);
        return palette.length - 1;
    };

    const blocks = new Uint32Array(256 * height);
    const liquids = new Uint32Array(256 * height);
    for (let x = 0; x < 16; x++) {
        for (let z = 0; z < 16; z++) {
            const column = (x * 16 + z) * height;
            for (let y = minY; y < minY + height; y++) {
                blocks[column + y - minY] = indexOf(chunk.getBlockRuntimeId(x, y, z, 0));
                liquids[column + y - minY] = indexOf(chunk.getBlockRuntimeId(x, y, z, 1));
            }
        }
    }

    const cellsY = height / 4;
    const biomes = new Uint16Array(16 * cellsY);
    for (let cellX = 0; cellX < 4; cellX++) {
        for (let cellZ = 0; cellZ < 4; cellZ++) {
            for (let cellY = 0; cellY < cellsY; cellY++) {
                biomes[(cellX * 4 + cellZ) * cellsY + cellY] = chunk.getBiome(cellX * 4, minY + cellY * 4, cellZ * 4);
            }
        }
    }

    const blockEntities = [...chunk.getBlockEntities()]
        .map((entity) => {
            const at = entity.getPosition();
            const nbt = new BinaryStream();
            entity.toNBT().writeToStream(nbt, ByteOrder.LITTLE_ENDIAN);
            return `${entity.getId()}@${at.getX()},${at.getY()},${at.getZ()} ${nbt.getBuffer().toString('hex')}`;
        })
        .sort();

    const entitySpawns = chunk
        .getEntitySpawns()
        .map((spawn) => `${spawn.type}@${spawn.x},${spawn.y},${spawn.z} yaw=${spawn.yaw ?? 0}`)
        .sort();

    return {
        palette,
        blocks,
        liquids,
        biomes,
        heightmap: chunk.heightmap(),
        blockEntities,
        entitySpawns,
        minY,
        height
    };
};

/**
 * Run-length encodes a slice of palette indices as alternating index and run length.
 *
 * @param indices - The whole chunk's indices.
 * @param runLength - How many entries each column contributes, so runs never cross a column.
 */
const encodeRuns = (indices: Uint32Array, runLength: number): number[] => {
    const runs: number[] = [];
    for (let start = 0; start < indices.length; start += runLength) {
        let value = indices[start]!;
        let count = 0;
        for (let at = start; at < start + runLength; at++) {
            if (indices[at] === value) {
                count += 1;
                continue;
            }
            runs.push(value, count);
            value = indices[at]!;
            count = 1;
        }
        runs.push(value, count);
    }
    return runs;
};

/** The same encoding over biome ids, which are values rather than palette indices. */
const encodeBiomeRuns = (biomes: Uint16Array): number[] => {
    const runs: number[] = [];
    let value = biomes[0]!;
    let count = 0;
    for (const biome of biomes) {
        if (biome === value) {
            count += 1;
            continue;
        }
        runs.push(value, count);
        value = biome;
        count = 1;
    }
    runs.push(value, count);
    return runs;
};

/** Run-length encoded state names, so the digest moves only when the generation does. */
const namedRuns = function* (
    reading: ChunkReading,
    indices: Uint32Array,
    runLength: number
): Generator<string, void, undefined> {
    for (const [at, value] of encodeRuns(indices, runLength).entries()) {
        yield at % 2 === 0 ? `${reading.palette[value]}\u0000` : `${value}\u0001`;
    }
};

/** How many blocks of each state the chunk holds on layer 0. */
const censusOf = (reading: ChunkReading): Record<string, number> => {
    const counts = new Uint32Array(reading.palette.length);
    for (const index of reading.blocks) counts[index] = (counts[index] ?? 0) + 1;

    const census: Record<string, number> = {};
    for (const [index, name] of reading.palette.entries()) {
        const count = counts[index]!;
        if (count > 0) census[name] = count;
    }
    return Object.fromEntries(Object.entries(census).sort(([left], [right]) => left.localeCompare(right)));
};

const sectionDigests = (reading: ChunkReading): string[] => {
    const sections = reading.height / 16;
    const digests: string[] = [];
    for (let section = 0; section < sections; section++) {
        const slice = new Uint32Array(256 * 16);
        for (let column = 0; column < 256; column++) {
            const from = column * reading.height + section * 16;
            slice.set(reading.blocks.subarray(from, from + 16), column * 16);
        }
        digests.push(sha(namedRuns(reading, slice, 16)));
    }
    return digests;
};

/** One captured chunk: the digest row, and the whole chunk when the plan asks for it. */
export interface CapturedChunk {
    readonly digest: ChunkDigest;
    readonly sample?: WholeChunkSample;
    /** The census, kept separately so the caller can total it without reparsing the digest. */
    readonly census: Readonly<Record<string, number>>;
}

/** Reduces one generated chunk to what the golden records. */
export const captureChunk = (entry: CorpusChunk, chunk: Chunk): CapturedChunk => {
    const reading = readChunk(chunk);
    const census = censusOf(reading);
    const digest: ChunkDigest = {
        id: entry.id,
        seed: entry.seed,
        chunkX: entry.chunkX,
        chunkZ: entry.chunkZ,
        tier: entry.tier,
        digests: {
            blocks: sha(namedRuns(reading, reading.blocks, reading.height)),
            sections: sectionDigests(reading),
            liquids: sha(namedRuns(reading, reading.liquids, reading.height)),
            biomes: sha([encodeBiomeRuns(reading.biomes).join(',')]),
            heightmap: sha([reading.heightmap.join(',')]),
            blockEntities: sha(reading.blockEntities),
            entitySpawns: sha(reading.entitySpawns)
        },
        census,
        blockEntities: reading.blockEntities.length,
        entitySpawns: reading.entitySpawns.length
    };

    if (entry.whole !== true) return { digest, census };

    return {
        digest,
        census,
        sample: {
            id: entry.id,
            palette: reading.palette,
            blocks: encodeRuns(reading.blocks, reading.height),
            liquids: encodeRuns(reading.liquids, reading.height),
            biomes: encodeBiomeRuns(reading.biomes),
            heightmap: [...reading.heightmap],
            blockEntities: reading.blockEntities,
            entitySpawns: reading.entitySpawns
        }
    };
};

/** Builds the generator one corpus chunk is produced by, and nothing else is. */
const generatorFor = (environment: GenerationEnvironment, tier: CorpusChunk['tier']): DataDrivenGenerator =>
    new DataDrivenGenerator({
        registries: environment.registries,
        templates: environment.templates,
        ...(tier === 'terrain' ? { decorate: false } : {})
    });

/** Generates one corpus chunk under the capture protocol and reduces it. */
export const generateCorpusChunk = async (
    environment: GenerationEnvironment,
    entry: CorpusChunk
): Promise<CapturedChunk> => {
    const generator = generatorFor(environment, entry.tier);
    return captureChunk(entry, await generator.generateChunk(entry.chunkX, entry.chunkZ, BigInt(entry.seed)));
};

/** Every structure start the placement scan reaches, deduplicated and ordered. */
export const captureStructures = (
    environment: GenerationEnvironment
): { placements: StructurePlacement[]; unbuilt: string[] } => {
    const placements = new Map<string, StructurePlacement>();
    const unbuilt = new Set<string>();

    for (const seed of STRUCTURE_SCAN_SEEDS) {
        // The plan numbers its seeds so the golden can hold them; the generator wants the long.
        const worldSeed = BigInt(seed);
        const generator = new DataDrivenGenerator({
            registries: environment.registries,
            templates: environment.templates
        });

        for (let chunkX = -STRUCTURE_SCAN_RADIUS; chunkX < STRUCTURE_SCAN_RADIUS; chunkX++) {
            for (let chunkZ = -STRUCTURE_SCAN_RADIUS; chunkZ < STRUCTURE_SCAN_RADIUS; chunkZ++) {
                for (const start of generator.structureStartsAt(chunkX, chunkZ, worldSeed)) {
                    placements.set(`${seed}/${start.structure}@${start.chunkX},${start.chunkZ}`, {
                        seed,
                        structure: start.structure,
                        set: start.set,
                        chunkX: start.chunkX,
                        chunkZ: start.chunkZ,
                        step: start.step,
                        origin: [start.origin.x, start.origin.y, start.origin.z],
                        box: [
                            start.boundingBox.minX,
                            start.boundingBox.minY,
                            start.boundingBox.minZ,
                            start.boundingBox.maxX,
                            start.boundingBox.maxY,
                            start.boundingBox.maxZ
                        ],
                        pieces: start.pieces.length
                    });
                }
            }
        }

        for (const type of generator.unbuiltStructureTypes(worldSeed)) unbuilt.add(type);
    }

    return {
        placements: [...placements.entries()].sort(([left], [right]) => left.localeCompare(right)).map(([, it]) => it),
        unbuilt: [...unbuilt].sort()
    };
};

/** What one run of the whole corpus produced. */
export interface CapturedCorpus {
    readonly chunks: readonly ChunkDigest[];
    readonly samples: readonly WholeChunkSample[];
    readonly structures: readonly StructurePlacement[];
    readonly unbuiltStructureTypes: readonly string[];
    /** Blocks of each state across every decorated chunk, which is the feature and ore census. */
    readonly blockCounts: Readonly<Record<string, number>>;
    readonly dimension: { readonly minY: number; readonly height: number };
    /** How long the run took, which is the number the corpus is budgeted against. */
    readonly elapsedMs: number;
}

/**
 * Generates and reduces the whole corpus.
 *
 * @param environment - The Java data, loaded once by {@link openGeneration}.
 * @param onChunk - Called after each chunk, for a capture script that wants progress.
 */
export const captureCorpus = async (
    environment: GenerationEnvironment,
    onChunk?: (entry: CorpusChunk, elapsedMs: number) => void
): Promise<CapturedCorpus> => {
    const started = performance.now();
    const chunks: ChunkDigest[] = [];
    const samples: WholeChunkSample[] = [];
    const blockCounts = new Map<string, number>();
    let minY = 0;
    let height = 0;

    for (const entry of CORPUS_CHUNKS) {
        const at = performance.now();
        const generator = generatorFor(environment, entry.tier);
        const chunk = await generator.generateChunk(entry.chunkX, entry.chunkZ, BigInt(entry.seed));
        minY = chunk.getMinY();
        height = chunk.getMaxY() - minY + 1;

        const captured = captureChunk(entry, chunk);
        chunks.push(captured.digest);
        if (captured.sample !== undefined) samples.push(captured.sample);
        if (entry.tier === 'full') {
            for (const [state, count] of Object.entries(captured.census)) {
                blockCounts.set(state, (blockCounts.get(state) ?? 0) + count);
            }
        }

        onChunk?.(entry, performance.now() - at);
    }

    const structures = captureStructures(environment);

    return {
        chunks,
        samples,
        structures: structures.placements,
        unbuiltStructureTypes: structures.unbuilt,
        blockCounts: Object.fromEntries([...blockCounts].sort(([left], [right]) => left.localeCompare(right))),
        dimension: { minY, height },
        elapsedMs: performance.now() - started
    };
};
