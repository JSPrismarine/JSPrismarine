import { itemDefinition, ItemStack, loadItemTypes } from '@jsprismarine/items';
import { describe, expect, it } from 'vitest';

import vectorsJson from '../vectors/formulas.json';
import {
    applyUnbreaking,
    float,
    attackDamage,
    attackSpeedOf,
    attackStrengthScale,
    baseAttackDamageOf,
    breakTicks,
    correctForDrops,
    destroyProgress,
    digSpeedAmplification,
    isArmorForUnbreaking,
    isDamageable,
    miningEfficiencyOf,
    miningFatigueAmplification,
    miningSpeed,
    spendDurability,
    submergedMiningSpeedOf,
    toolSpeedFor
} from './formulas';
import { createTestWorld, testBlock } from './testing';

/** One row of each vector table the Java oracle writes. */
interface FormulaVectors {
    readonly mining: readonly {
        toolSpeed: number;
        miningEfficiency: number;
        digSpeedAmplifier: number;
        miningFatigueAmplifier: number;
        blockBreakSpeed: number;
        eyeInWater: boolean;
        submergedMiningSpeed: number;
        onGround: boolean;
        speed: number;
    }[];
    readonly progress: readonly {
        speed: number;
        hardness: number;
        correctToolForDrops: boolean;
        progress: number;
    }[];
    readonly charge: readonly { ticksSinceAttack: number; attackSpeed: number; scale: number }[];
    readonly attack: readonly {
        baseAttackDamage: number;
        attackStrengthScale: number;
        enchantmentBonus: number;
        critical: boolean;
        damage: number;
    }[];
    readonly unbreaking: readonly { level: number; armor: boolean; chance: number }[];
}

// The vector file is the oracle's output, generated by `utils/oracle/run.mjs`
// against the pinned 26.3 jar; its shape is the dumper's contract.
const vectors = vectorsJson as unknown as FormulaVectors;

const { registry } = loadItemTypes();
const stackOf = (identifier: string, count = 1): ItemStack => new ItemStack(registry.holder(identifier), count);

describe('miningSpeed', () => {
    it('reproduces every value the Java oracle computed', () => {
        const wrong = vectors.mining.filter(
            (vector) =>
                miningSpeed({
                    toolSpeed: vector.toolSpeed,
                    miningEfficiency: vector.miningEfficiency,
                    ...(vector.digSpeedAmplifier >= 0 ? { digSpeedAmplifier: vector.digSpeedAmplifier } : {}),
                    ...(vector.miningFatigueAmplifier >= 0
                        ? { miningFatigueAmplifier: vector.miningFatigueAmplifier }
                        : {}),
                    blockBreakSpeed: vector.blockBreakSpeed,
                    submergedMiningSpeed: vector.submergedMiningSpeed,
                    eyeInWater: vector.eyeInWater,
                    onGround: vector.onGround
                }) !== float(vector.speed)
        );
        expect(wrong).toEqual([]);
        expect(vectors.mining.length).toBeGreaterThan(500);
    });

    it('leaves a bare hand and an incorrect tool outside the Efficiency bonus', () => {
        expect(miningSpeed({ toolSpeed: 1, miningEfficiency: 26 })).toBe(1);
        expect(miningSpeed({ toolSpeed: 1.0001, miningEfficiency: 26 })).toBeCloseTo(27.0001, 4);
    });

    it('divides by five in the air and scales by the submerged attribute in water', () => {
        expect(miningSpeed({ toolSpeed: 10, onGround: false })).toBe(2);
        expect(miningSpeed({ toolSpeed: 10, eyeInWater: true })).toBeCloseTo(2, 6);
        expect(miningSpeed({ toolSpeed: 10, eyeInWater: true, submergedMiningSpeed: 1 })).toBe(10);
    });
});

describe('destroyProgress', () => {
    it('reproduces every value the Java oracle computed', () => {
        const wrong = vectors.progress.filter(
            (vector) =>
                destroyProgress(float(vector.speed), vector.hardness, vector.correctToolForDrops) !==
                float(vector.progress)
        );
        expect(wrong).toEqual([]);
    });

    it('reports no progress on an unbreakable block', () => {
        expect(destroyProgress(100, -1, true)).toBe(0);
        expect(breakTicks(100, -1, true)).toBe(Number.POSITIVE_INFINITY);
    });

    it('takes the wiki figure of 7.5 seconds to break stone with a bare hand', () => {
        // Stone is hardness 1.5 and a bare hand is never correct for drops:
        // 1 / 1.5 / 100 is 0.00667 a tick, which is 150 ticks.
        expect(breakTicks(miningSpeed({ toolSpeed: 1 }), 1.5, false)).toBe(150);
        // A wooden pickaxe is speed 2 and correct, which is 1 / (2 / 1.5 / 30).
        expect(breakTicks(miningSpeed({ toolSpeed: 2 }), 1.5, true)).toBe(23);
    });
});

describe('attackStrengthScale', () => {
    it('reproduces every value the Java oracle computed', () => {
        const wrong = vectors.charge.filter(
            (vector) => attackStrengthScale(vector.ticksSinceAttack, vector.attackSpeed) !== float(vector.scale)
        );
        expect(wrong).toEqual([]);
    });

    it('needs the full cooldown to reach one', () => {
        // A sword's 1.6 attack speed is a 12.5 tick delay.
        expect(attackStrengthScale(0, 1.6)).toBeCloseTo(0.04, 5);
        expect(attackStrengthScale(12, 1.6)).toBe(1);
    });
});

describe('attackDamage', () => {
    it('reproduces every value the Java oracle computed', () => {
        const wrong = vectors.attack.filter(
            (vector) =>
                attackDamage({
                    baseAttackDamage: vector.baseAttackDamage,
                    attackStrengthScale: float(vector.attackStrengthScale),
                    enchantmentBonus: vector.enchantmentBonus,
                    critical: vector.critical
                }) !== float(vector.damage)
        );
        expect(wrong).toEqual([]);
    });

    it('defaults to a fully charged swing, which is the Bedrock cooldown choice', () => {
        expect(attackDamage({ baseAttackDamage: 7 })).toBe(7);
        expect(attackDamage({ baseAttackDamage: 7, critical: true })).toBe(10.5);
    });

    it('scales the enchantment bonus linearly and the base quadratically', () => {
        const half = attackDamage({ baseAttackDamage: 8, attackStrengthScale: 0.5, enchantmentBonus: 3 });
        expect(half).toBeCloseTo(8 * (0.2 + 0.25 * 0.8) + 0.5 * 3, 5);
    });

    it('adds the mace figure through the item bonus', () => {
        expect(attackDamage({ baseAttackDamage: 7, itemBonus: 15 })).toBe(22);
    });
});

describe('attack attributes read off a stack', () => {
    it('adds the item modifier to the player base', () => {
        expect(baseAttackDamageOf(stackOf('minecraft:diamond_sword'))).toBe(7);
        expect(baseAttackDamageOf(stackOf('minecraft:diamond_axe'))).toBe(9);
        expect(baseAttackDamageOf(stackOf('minecraft:apple'))).toBe(1);
    });

    it('reads the attack speed the weapon slows the player to', () => {
        expect(attackSpeedOf(stackOf('minecraft:diamond_sword'))).toBeCloseTo(1.6, 5);
        expect(attackSpeedOf(stackOf('minecraft:apple'))).toBe(4);
    });
});

describe('mining attributes from enchantments', () => {
    it('gives Efficiency the level squared plus one', () => {
        expect([0, 1, 2, 3, 4, 5].map(miningEfficiencyOf)).toEqual([0, 2, 5, 10, 17, 26]);
    });

    it('takes Aqua Affinity from the 0.2 penalty to no penalty at all', () => {
        expect(submergedMiningSpeedOf(0)).toBeCloseTo(0.2, 6);
        expect(submergedMiningSpeedOf(1)).toBeCloseTo(1, 6);
    });

    it('takes the strongest of Haste and Conduit Power and reads Mining Fatigue', () => {
        const effects = [
            { id: 'minecraft:haste', amplifier: 1 },
            { id: 'minecraft:conduit_power', amplifier: 2 },
            { id: 'minecraft:mining_fatigue', amplifier: 3 }
        ];
        expect(digSpeedAmplification(effects)).toBe(2);
        expect(miningFatigueAmplification(effects)).toBe(3);
        expect(digSpeedAmplification([])).toBeUndefined();
        expect(miningFatigueAmplification([])).toBeUndefined();
    });
});

describe('tool rules', () => {
    const world = createTestWorld({
        tags: {
            'minecraft:mineable/pickaxe': ['minecraft:stone', 'minecraft:iron_ore'],
            'minecraft:incorrect_for_diamond_tool': []
        }
    });

    it('takes the speed of the first matching rule and one without a tool', () => {
        expect(toolSpeedFor(stackOf('minecraft:diamond_pickaxe'), testBlock('minecraft:stone'), world)).toBe(8);
        expect(toolSpeedFor(stackOf('minecraft:diamond_pickaxe'), testBlock('minecraft:dirt'), world)).toBe(1);
        expect(toolSpeedFor(stackOf('minecraft:apple'), testBlock('minecraft:stone'), world)).toBe(1);
    });

    it('drops the block only when a rule says so', () => {
        expect(correctForDrops(stackOf('minecraft:diamond_pickaxe'), testBlock('minecraft:stone'), world)).toBe(true);
        expect(correctForDrops(stackOf('minecraft:diamond_pickaxe'), testBlock('minecraft:dirt'), world)).toBe(false);
        expect(correctForDrops(stackOf('minecraft:apple'), testBlock('minecraft:stone'), world)).toBe(false);
    });

    it('reads the sword cobweb rule, which is a tool rule on a weapon', () => {
        const cobwebWorld = createTestWorld({ tags: {} });
        expect(toolSpeedFor(stackOf('minecraft:diamond_sword'), testBlock('minecraft:cobweb'), cobwebWorld)).toBe(15);
    });
});

describe('spendDurability', () => {
    const never = () => 0.99;
    const always = () => 0;

    it('refuses to damage an item with no durability', () => {
        const apple = stackOf('minecraft:apple', 3);
        expect(isDamageable(apple)).toBe(false);
        const spend = spendDurability(apple, 1, { random: never });
        expect(spend).toMatchObject({ amount: 0, broke: false });
    });

    it('spends one point and reports the new damage', () => {
        const pickaxe = stackOf('minecraft:diamond_pickaxe');
        const spend = spendDurability(pickaxe, 1, { random: never });
        expect(spend.amount).toBe(1);
        expect(spend.damage).toBe(1);
        expect(spend.broke).toBe(false);
        expect(spend.stack.get('minecraft:damage')).toBe(1);
        // The argument is left alone, which is what lets a hook decline.
        expect(pickaxe.get('minecraft:damage')).toBe(0);
    });

    it('breaks the item on the last point and shrinks the stack', () => {
        const shears = stackOf('minecraft:shears');
        shears.set('minecraft:damage', 237);
        const spend = spendDurability(shears, 1, { random: never });
        expect(spend.broke).toBe(true);
        expect(spend.damage).toBe(238);
        expect(spend.stack.count).toBe(0);
    });

    it('spends nothing in creative', () => {
        expect(spendDurability(stackOf('minecraft:shears'), 1, { random: never, creative: true }).amount).toBe(0);
    });

    it('lets Unbreaking swallow the hit', () => {
        const pickaxe = stackOf('minecraft:diamond_pickaxe');
        pickaxe.set('minecraft:enchantments', { 'minecraft:unbreaking': 3 });
        expect(spendDurability(pickaxe, 1, { random: always }).amount).toBe(0);
        expect(spendDurability(pickaxe, 1, { random: never }).amount).toBe(1);
    });

    it('rolls once per point of damage', () => {
        // Three quarters is Unbreaking III on a tool, so a roll under it drops
        // the point and a roll over it keeps it.
        const rolls = [0.1, 0.9];
        let index = 0;
        const pickaxe = stackOf('minecraft:diamond_pickaxe');
        pickaxe.set('minecraft:enchantments', { 'minecraft:unbreaking': 3 });
        expect(spendDurability(pickaxe, 2, { random: () => rolls[index++]! }).amount).toBe(1);
    });

    it('matches the oracle chances, and halves the benefit on armor', () => {
        for (const vector of vectors.unbreaking) {
            // A roll below the chance drops the point; a roll on it keeps it.
            const onChance = applyUnbreaking(1, vector.level, vector.armor, () => float(vector.chance));
            const belowChance = applyUnbreaking(1, vector.level, vector.armor, () => float(vector.chance) - 1e-9);
            expect([onChance, belowChance]).toEqual([1, 0]);
        }
        expect(isArmorForUnbreaking(stackOf('minecraft:diamond_chestplate'))).toBe(true);
        expect(isArmorForUnbreaking(stackOf('minecraft:diamond_pickaxe'))).toBe(false);
    });
});

