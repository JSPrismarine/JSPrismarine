/**
 * The level behind a test world.
 *
 * A `World` reaches its seed, clock, game rules, weather, spawn and player records through its
 * `Level`, so every test that builds a world needs one. Two shapes cover them:
 *
 * - {@link fakeLevel} is a double with the save-level state in memory and no provider behind
 *   it, for a test that drives one world directly and never opens a save.
 * - {@link testLevel} is a real `Level` over a real provider whose one stem builds the
 *   generator the test hands it, for a test that saves and reloads through LevelDB.
 *
 * Both are ordinary source rather than test files, so `tsc` checks their members against the
 * real `Level` and the next member a world reaches for is added in one place.
 */
import type { Vector3 } from '@jsprismarine/math';
import type { DimensionDefinitionFields } from '@jsprismarine/protocol';
import type { LevelStem } from '@jsprismarine/worldgen';
import { OVERWORLD_STEM_ID } from '@jsprismarine/worldgen';

import type { WorldConfig, WorldPlayerData } from '../config/JsonConfigTypes';
import type Server from '../Server';
import { Dimensions } from '../world/Dimension';
import type { DimensionType } from '../world/Dimension';
import GameRuleManager from '../world/GameRuleManager';
import type { Generator } from '../world/Generator';
import { GeneratorFactories } from '../world/GeneratorFactories';
import { Level } from '../world/Level';
import type { DimensionLoad } from '../world/Level';
import type BaseProvider from '../world/providers/BaseProvider';
import type Provider from '../world/providers/Provider';
import { WorldWeather } from '../world/Weather';
import type { World } from '../world/World';
import type { LegacyWorldEntity } from '../world/WorldPersistence';
import { testEntityServer } from './entityServer';
import { stub } from './stub.test.helper';

/** The generator kind {@link testLevel} registers the test's generator under. */
export const TEST_GENERATOR_KIND = 'jsprismarine:test';

/** The one stem a test level has: the Overworld, generated by the test's generator. */
export const TEST_OVERWORLD_STEM: LevelStem = {
    type: Dimensions.Overworld.id,
    generator: { type: TEST_GENERATOR_KIND, settings: undefined }
};

/** What a test says about the level behind its world. */
export interface FakeLevelOptions {
    readonly name?: string;
    readonly seed?: bigint;
    /** The server the level and its worlds reach. Defaults to {@link testEntityServer}. */
    readonly server?: Server;
    /** The provider a world reads chunks through. Left out, the double has none. */
    readonly provider?: BaseProvider & Provider;
    /** Where the clock starts. */
    readonly ticks?: number;
    /** The rules the level answers. Defaults to a real manager with the defaults. */
    readonly gameRules?: GameRuleManager;
    /** The world spawn the level already knows. */
    readonly spawn?: Vector3 | null;
    /** The stems the double reports, by stem id. Defaults to one Overworld stem built by the test generator. */
    readonly stems?: ReadonlyMap<string, LevelStem>;
    /** The dimension types the double resolves a stem's type to, by type id. */
    readonly dimensionTypes?: ReadonlyMap<string, DimensionType>;
    /** What the double announces through `DimensionData`. Defaults to nothing, as a vanilla level. */
    readonly customDimensionDefinitions?: readonly DimensionDefinitionFields[];
    /** Player records the level answers, by key. A save writes into the same map. */
    readonly playerData?: Map<string, Partial<WorldPlayerData>>;
    readonly legacyEntities?: readonly LegacyWorldEntity[];
    /**
     * The worlds the double reports as loaded, for a test that ticks through the level or asks
     * it for one dimension's world. `world(id)` answers the one whose dimension type has that id.
     */
    readonly worlds?: () => readonly World[];
}

/**
 * A level with its save-level state in memory and nothing on disk.
 *
 * The clock, rules, weather and spawn are real objects, so a test can set a rule or advance the
 * clock and the world sees it. Saving the level data does nothing; a player record goes into
 * the map the test passed, or nowhere.
 */
export const fakeLevel = (options: FakeLevelOptions = {}): Level => {
    const server = options.server ?? testEntityServer();
    const gameRules = options.gameRules ?? new GameRuleManager(server);
    const weather = new WorldWeather({
        cycleAllowed: () => gameRules.getGameRule('doWeatherCycle')?.[0] !== false,
        randomInt: (bound) => Math.floor(Math.random() * bound),
        broadcast: () => {}
    });
    const worlds = options.worlds ?? (() => []);
    let ticks = options.ticks ?? 0;
    let spawn = options.spawn ?? null;

    return stub<Level>({
        name: options.name ?? 'test',
        seed: options.seed ?? 0n,
        getName: () => options.name ?? 'test',
        getServer: () => server,
        getProvider: () => {
            if (options.provider === undefined) throw new Error('the fake level was built without a provider');
            return options.provider;
        },
        getStems: () => options.stems ?? new Map([[OVERWORLD_STEM_ID, TEST_OVERWORLD_STEM]]),
        getDimensionTypes: () => options.dimensionTypes ?? new Map(),
        getTicks: () => ticks,
        setTicks: (tick) => {
            ticks = tick;
        },
        getGameRuleManager: () => gameRules,
        getWeather: () => weather,
        getSpawn: () => spawn,
        setSpawn: (at) => {
            spawn = at;
        },
        legacyEntities: () => options.legacyEntities ?? [],
        isClosed: () => false,
        loadedWorld: () => undefined,
        worlds: function* () {
            yield* worlds();
        },
        world: async (dimensionId) => {
            const found = worlds().find((world) => world.getDimension().id === dimensionId);
            if (found === undefined) throw new Error(`the fake level has no ${dimensionId} world`);
            return found;
        },
        customDimensionDefinitions: () => [...(options.customDimensionDefinitions ?? [])],
        update: async (tick) => {
            ticks++;
            weather.tick(ticks);
            await Promise.all(worlds().map(async (world) => world.update(tick)));
        },
        save: async () => {},
        saveLevelData: async () => {},
        getPlayerData: async (key) => options.playerData?.get(key) ?? null,
        savePlayerData: async (key, data) => {
            options.playerData?.set(key, data);
        }
    });
};

/** What a test says about a real level over a real provider. */
export interface TestLevelOptions {
    readonly name: string;
    /** The level folder, where the legacy `level.json` and the fallback player records live. */
    readonly path: string;
    readonly server: Server;
    readonly provider: BaseProvider & Provider;
    readonly seed?: bigint;
    /** What the Overworld stem builds to. */
    readonly generator: Generator;
    /**
     * The world spawn, known before any world is built, so enabling the Overworld skips the
     * search for dry land and the chunks it would generate.
     */
    readonly spawn?: Vector3;
    /** When the Overworld is built. Defaults to lazy, so a test opens the save without a world. */
    readonly load?: DimensionLoad;
    readonly config?: WorldConfig;
    readonly onWorldBuilt?: (world: World) => void;
}

/**
 * A real level whose one stem, the Overworld, builds through the generator the test hands it.
 *
 * Enabling it opens the provider for real; `level.world('minecraft:overworld')` then builds
 * and enables the world the way `WorldManager` does, and `level.disable()` saves and closes
 * the provider.
 */
export const testLevel = (options: TestLevelOptions): Level => {
    const level = new Level({
        name: options.name,
        path: options.path,
        server: options.server,
        provider: options.provider,
        seed: options.seed ?? 1234n,
        stems: new Map([[OVERWORLD_STEM_ID, TEST_OVERWORLD_STEM]]),
        dimensionTypes: new Map([[Dimensions.Overworld.id, Dimensions.Overworld.java]]),
        load: new Map([[OVERWORLD_STEM_ID, options.load ?? 'lazy']]),
        factories: new GeneratorFactories([{ kind: TEST_GENERATOR_KIND, build: () => options.generator }]),
        worldgen: () => {
            throw new Error('A test level never reads the Java registries');
        },
        config: options.config,
        onWorldBuilt: options.onWorldBuilt
    });
    if (options.spawn !== undefined) level.setSpawn(options.spawn);
    return level;
};
