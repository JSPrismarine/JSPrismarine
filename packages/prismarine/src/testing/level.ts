/** The generator kind {@link testLevel} registers the test's generator under. */
export const TEST_GENERATOR_KIND = 'jsprismarine:test';

/** The one stem a test level has: the Overworld, generated by the test's generator. */
export const TEST_OVERWORLD_STEM: LevelStem = {
    type: Dimensions.Overworld.id,
    generator: { type: TEST_GENERATOR_KIND, settings: undefined }
};

/** What a test says about the level behind its world. */
export interface FakeLevelOptions {
    readonly name?: string;
    readonly seed?: bigint;
    /** The server the level and its worlds reach. Defaults to {@link testEntityServer}. */
    readonly server?: Server;
    /** The provider a world reads chunks through. Left out, the double has none. */
    readonly provider?: BaseProvider;
    /** Where the clock starts. */
    readonly ticks?: number;
    /** The rules the level answers. Defaults to a real manager with the defaults. */
    readonly gameRules?: GameRuleManager;
    /** The world spawn the level already knows. */
    readonly spawn?: Vector3 | null;
    /** The stems the double reports, by stem id. Defaults to one Overworld stem built by the test generator. */
    readonly stems?: ReadonlyMap<string, LevelStem>;
    /** The dimension types the double resolves a stem's type to, by type id. */
    readonly dimensionTypes?: ReadonlyMap<string, DimensionType>;
    /** What the double announces through `DimensionData`. Defaults to nothing, as a vanilla level. */
    readonly customDimensionDefinitions?: readonly DimensionDefinitionFields[];
    /** Player records the level answers, by key. A save writes into the same map. */
    readonly playerData?: Map<string, Partial<WorldPlayerData>>;
    readonly legacyEntities?: readonly LegacyWorldEntity[];
    /**
     * The worlds the double reports as loaded, for a test that ticks through the level or asks
     * it for one dimension's world. `world(id)` answers the one whose dimension type has that id.
     */
    readonly worlds?: () => readonly World[];
    /** The Bedrock experiments the level runs with. Defaults to none. */
    readonly experiments?: readonly WorldExperiment[];
}

/**
 * A level with its save-level state in memory and nothing on disk.
 *
 * The clock, rules, weather and spawn are real objects, so a test can set a rule or advance the
 * clock and the world sees it. Saving the level data does nothing; a player record goes into
 * the map the test passed, or nowhere.
 */
export const fakeLevel = (options: FakeLevelOptions = {}): Level => {
    const server = options.server ?? testEntityServer();
    const gameRules = options.gameRules ?? new GameRuleManager(server);
    const weather = new WorldWeather({
        cycleAllowed: () => gameRules.getGameRule('doWeatherCycle')?.[0] !== false,
        randomInt: (bound) => Math.floor(Math.random() * bound),
        broadcast: () => {}
    });
    const worlds = options.worlds ?? (() => []);
    const clock = new LevelClock(() => gameRuleValue(gameRules, ADVANCE_TIME) !== false);
    clock.setGameTime(options.ticks ?? 0);
    let spawn = options.spawn ?? null;
    const stems = options.stems ?? new Map([[OVERWORLD_STEM_ID, TEST_OVERWORLD_STEM]]);
    const world = async (dimensionId: string): Promise<World> => {
        const found = worlds().find((each) => each.getDimension().id === dimensionId);
        if (found === undefined) throw new PrismarineServerErrors.FakeLevelHasNoWorld({ dimensionId });
        return found;
    };
    // A real save over the provider, without the level's own state, so a world that saves
    // through its level writes its chunks the way it would under a real one.
    const provider = options.provider;
    const saves =
        provider === undefined
            ? undefined
            : new LevelSave({
                  name: options.name ?? 'test',
                  provider: () => provider,
                  logger: () => server.getLogger(),
                  // A provider that keeps no players hands the cut's records here, as a real level
                  // writes them to its fallback files.
                  savePlayers: async (records) => {
                      for (const [key, record] of records) options.playerData?.set(key, record);
                  }
              });
    const respawnSearch = new RespawnSearch({
        hasStem: (stemId) => stems.has(stemId),
        world,
        built: (dimensionId) => worlds().find((each) => each.getDimension().id === dimensionId),
        worldSpawn: () => server.getWorldManager().getEntryWorld()
    });

    const referenced = new Set<string>();
    // The level's maps by id, numbered as a real level numbers them.
    const maps = new Map<number, SavedMap>();
    const addMap = (map: SavedMap): number => {
        const id = maps.size + 1;
        maps.set(id, map);
        return id;
    };
    return stub<Level>({
        name: options.name ?? 'test',
        seed: options.seed ?? 0n,
        getName: () => options.name ?? 'test',
        getServer: () => server,
        getExperiments: () => options.experiments ?? [],
        isHardcore: () => false,
        getProvider: () => {
            if (options.provider === undefined) throw new PrismarineServerErrors.FakeLevelWithoutProvider();
            return options.provider;
        },
        getStems: () => stems,
        getDimensionTypes: () => options.dimensionTypes ?? new Map(),
        getTicks: () => clock.getGameTime(),
        setTicks: (tick) => clock.setGameTime(tick),
        getDayTime: () => clock.getDayTime(),
        setDayTime: (time) => clock.setDayTime(time),
        isDayTimePaused: () => clock.isPaused(),
        setDayTimePaused: (paused) => clock.setPaused(paused),
        getGameRuleManager: () => gameRules,
        getWeather: () => weather,
        getSpawn: () => spawn,
        setSpawn: (at) => {
            spawn = at;
        },
        addMap,
        createMap: (request) => addMap(newSavedMap(request)),
        getMap: (id) => maps.get(id),
        isStructureReferenced: (start) => referenced.has(structureReferenceKey(start)),
        referenceStructure: (start) => {
            referenced.add(structureReferenceKey(start));
        },
        legacyEntities: () => options.legacyEntities ?? [],
        storedDragonFightState: () => undefined,
        isClosed: () => false,
        loadedWorld: () => undefined,
        readyWorld: (dimensionId) => worlds().find((each) => each.getDimension().id === dimensionId),
        worlds: function* () {
            yield* worlds();
        },
        world,
        getRespawnSearch: () => respawnSearch,
        customDimensionDefinitions: () => [...(options.customDimensionDefinitions ?? [])],
        update: (tick) => {
            clock.tick();
            weather.tick(clock.getGameTime());
            for (const world of worlds()) world.update(tick);
            saves?.tick(clock.getGameTime(), worlds());
        },
        save: async () => saves?.save(worlds()),
        saveWorlds: async (saved) => saves?.save(saved),
        saveLevelData: async () => {},
        getPlayerData: async (key) => options.playerData?.get(key) ?? null,
        savePlayerData: async (key, data) => {
            options.playerData?.set(key, data);
        }
    });
};

/** What a test says about the world {@link testWorld} builds. Every member is optional. */
export interface TestWorldOptions {
    readonly name?: string;
    /** Defaults to the level's server, or {@link testEntityServer} with no level either. */
    readonly server?: Server;
    /** Defaults to a {@link fakeLevel} over the server. */
    readonly level?: Level;
    readonly dimension?: DimensionType;
    /** Defaults to a generator with no members, for a test that never generates a chunk. */
    readonly generator?: Generator;
    readonly config?: WorldConfig;
}

/**
 * A world built by its own constructor over test doubles.
 *
 * Build every test world through this, never on `World.prototype`: the constructor makes each
 * map, set and system a world keeps, so a field `World` adds later is there in every test. A
 * test that needs a member to answer differently assigns it over the built world.
 */
export const testWorld = (options: TestWorldOptions = {}): World => {
    const server = options.server ?? options.level?.getServer() ?? testEntityServer();
    const name = options.name ?? 'test';
    return new World({
        name,
        path: name,
        server,
        level: options.level ?? fakeLevel({ server }),
        stem: TEST_OVERWORLD_STEM,
        generator: options.generator ?? stub<Generator>({}),
        dimension: options.dimension ?? Dimensions.Overworld,
        ...(options.config === undefined ? {} : { config: options.config })
    });
};

/** What a test says about a real level over a real provider. */
export interface TestLevelOptions {
    /** The level's UUID. Defaults to a new one. */
    readonly id?: string;
    readonly name: string;
    /** The level folder, where the legacy `level.json` and the fallback player records live. */
    readonly path: string;
    readonly server: Server;
    readonly provider: BaseProvider;
    readonly seed?: bigint;
    /** The custom dimension numbers the save keeps, as the world manager reads them before it opens the level. */
    readonly dimensionNumbers?: SavedDimensionNumbers;
    /** What the Overworld stem builds to. */
    readonly generator: Generator;
    /** What a Nether stem builds to. Left out, the level has no Nether. */
    readonly nether?: Generator;
    /**
     * The world spawn, known before any world is built, so enabling the Overworld skips the
     * search for dry land and the chunks it would generate.
     */
    readonly spawn?: Vector3;
    /** When the Overworld is built. Defaults to lazy, so a test opens the save without a world. */
    readonly load?: DimensionLoad;
    readonly config?: WorldConfig;
    readonly onWorldBuilt?: (world: World) => void;
}

/**
 * A real level whose one stem, the Overworld, builds through the generator the test hands it.
 *
 * Enabling it opens the provider for real; `level.world('minecraft:overworld')` then builds
 * and enables the world the way `WorldManager` does, and `level.disable()` saves and closes
 * the provider.
 */
export const testLevel = (options: TestLevelOptions): Level => {
    const nether = options.nether;
    const netherStem: LevelStem = {
        type: Dimensions.Nether.id,
        generator: { type: TEST_GENERATOR_KIND, settings: undefined }
    };
    const level = new Level({
        id: options.id ?? randomUUID(),
        name: options.name,
        path: options.path,
        server: options.server,
        provider: options.provider,
        seed: options.seed ?? 1234n,
        ...(options.dimensionNumbers === undefined ? {} : { dimensionNumbers: options.dimensionNumbers }),
        stems: new Map([
            [OVERWORLD_STEM_ID, TEST_OVERWORLD_STEM],
            ...(nether === undefined ? [] : ([[Dimensions.Nether.id, netherStem]] as const))
        ]),
        dimensionTypes: new Map([
            [Dimensions.Overworld.id, Dimensions.Overworld.java],
            ...(nether === undefined ? [] : ([[Dimensions.Nether.id, Dimensions.Nether.java]] as const))
        ]),
        load: new Map([
            [OVERWORLD_STEM_ID, options.load ?? 'lazy'],
            ...(nether === undefined ? [] : ([[Dimensions.Nether.id, 'lazy']] as const))
        ]),
        factories: new GeneratorFactories([
            {
                kind: TEST_GENERATOR_KIND,
                build: ({ dimension }) =>
                    nether !== undefined && dimension.id === Dimensions.Nether.id ? nether : options.generator
            },
            // The void dimensions scripts register.
            voidGeneratorFactory
        ]),
        worldgen: () => {
            throw new PrismarineServerErrors.TestLevelReadsJavaRegistries();
        },
        config: options.config,
        onWorldBuilt: options.onWorldBuilt
    });
    if (options.spawn !== undefined) level.setSpawn(options.spawn);
    return level;
};
