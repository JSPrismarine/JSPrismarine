export type PacketName = keyof typeof packetIds;

const byName = new Map<string, number>(Object.entries(packetIds));

/**
 * The 2193 wire id under a packet class name.
 * @param {string} name - the packet class name, for example `'LoginPacket'`.
 * @returns {number | undefined} the id, or `undefined` for a name 2193 does not list.
 */
export const netIdFor = (name: string): number | undefined => byName.get(name);
