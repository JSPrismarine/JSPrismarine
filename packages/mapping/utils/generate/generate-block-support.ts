/**
 * Generates `src/tables/<release>/blockSupport.json`: each Java block state's legacy solid flag and
 * face sturdiness, which `src/blockSupport.ts` answers for a Bedrock block state.
 *
 * The input is the `block_support.json` golden `dump:java` writes into `@jsprismarine/bedrock-data`
 * from the pinned jar, so this generator needs no fetched sources. The table stays keyed by Java
 * state: a Bedrock state answers with the bits of the Java state `bedrockBlockStateToJava` picks
 * for it, which keeps one rule for which of several collapsed Java states a Bedrock state is. The
 * generator checks that the golden covers every Java block of the release's block table with one
 * value per state, and writes only those blocks.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The pair resolver of the package that owns `sources.json`; generator scripts are not published.
import { resolveJavaBedrockPair } from '../../../bedrock-data/utils/java/release.ts';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
// `--java <release>` picks the tables' release directory, the default release when absent.
const pair = resolveJavaBedrockPair(process.argv);
const tablesDir = join(packageDir, 'src/tables', pair.java);
const repoRoot = resolve(packageDir, '../..');

/** One block's packed values, run-length encoded: a bare value or `[value, count]` runs. */
type Runs = number | (number | [number, number])[];

interface SupportGolden {
    faces: string[];
    supportTypes: string[];
    blocks: Record<string, Runs>;
}

interface BlocksTable {
    javaVersion: string;
    blocks: Record<string, { properties?: Record<string, string[]> }>;
}

const readJson = (path: string): unknown => JSON.parse(readFileSync(path, 'utf8'));

// The golden and the block table are parsed JSON; `javaGoldens.test.ts` in bedrock-data and
// this package's `tables.ts` document the shapes.
const golden = readJson(
    join(repoRoot, 'packages/bedrock-data/src/jsp/java', pair.java, 'block_support.json')
) as SupportGolden;
const blocksTable = readJson(join(tablesDir, 'blocks.json')) as BlocksTable;

/** How many states a run-length encoded block holds, or undefined for a single shared value. */
const runLength = (runs: Runs): number | undefined =>
    typeof runs === 'number'
        ? undefined
        : runs.reduce<number>((sum, run) => sum + (typeof run === 'number' ? 1 : run[1]), 0);

const lines: string[] = [];
for (const [javaId, block] of Object.entries(blocksTable.blocks)) {
    const runs = golden.blocks[javaId];
    if (runs === undefined) throw new Error(`${javaId} is in the mapping table but not in the support golden`);
    const states = Object.values(block.properties ?? {}).reduce((product, values) => product * values.length, 1);
    const length = runLength(runs);
    if (length !== undefined && length !== states) {
        throw new Error(`${javaId}: mapping table has ${states} states, support golden has ${length}`);
    }
    lines.push(`        ${JSON.stringify(javaId)}: ${JSON.stringify(runs)}`);
}

const notice = [
    'Generated by utils/generate/generate-block-support.ts. Do not edit; regenerate with',
    '`pnpm --filter @jsprismarine/mapping run generate:block-support`.',
    '',
    `Java ${blocksTable.javaVersion}'s legacy solid flag and face sturdiness per block state, from the jar ` +
        'dump golden in @jsprismarine/bedrock-data. Each state packs into one integer, in Java state order: ' +
        'the solid flag in bit 0, then one bit per face for each support type in turn, in the orders `faces` ' +
        'and `supportTypes` give. A bare value is shared by every state of the block, and `[value, count]` ' +
        'is a run of states.'
];

const body = [
    '{',
    `    "$notice": ${JSON.stringify(notice, null, 4).replaceAll('\n', '\n    ')},`,
    `    "javaVersion": ${JSON.stringify(blocksTable.javaVersion)},`,
    `    "faces": ${JSON.stringify(golden.faces)},`,
    `    "supportTypes": ${JSON.stringify(golden.supportTypes)},`,
    '    "blocks": {',
    lines.join(',\n'),
    '    }',
    '}',
    ''
].join('\n');

const path = join(tablesDir, 'blockSupport.json');
writeFileSync(path, body);
console.log(`Wrote ${path}: ${lines.length} Java blocks`);
