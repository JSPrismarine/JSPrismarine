/** One release `dump:java-protocol` has written, as its `release.ts` records it. */
export interface DumpedRelease {
    readonly version: string;
    readonly protocolVersion: number;
}

/** Whether a protocol number is a snapshot's or a pre-release's, which has bit 30 set. */
export const isSnapshotProtocol = (protocolVersion: number): boolean => (protocolVersion & 0x4000_0000) !== 0;

/** A release id as an identifier, such as `26_3` for 26.3. */
const identifierOf = (version: string): string => version.replace(/[^\w]/g, '_').toUpperCase();

/** The releases the server speaks: every dumped release but snapshots, newest first. */
const spoken = (releases: readonly DumpedRelease[]): { newest: DumpedRelease; older: DumpedRelease[] } => {
    const [newest, ...older] = releases
        .filter(({ protocolVersion }) => !isSnapshotProtocol(protocolVersion))
        .sort((a, b) => b.protocolVersion - a.protocolVersion);
    if (newest === undefined) throw new Error('no release to speak: every dumped release is a snapshot');
    return { newest, older };
};

/** The header of the two modules every dump rewrites, which name no one release. */
const registryHeader =
    '// Generated by `pnpm --filter @jsprismarine/bedrock-data run dump:java-protocol`. Do not edit.\n';

/**
 * The source of `javaReleases.ts`: every dumped release but snapshots, newest first. A snapshot's
 * directory stays dumped for its bring-up, and the server speaks it once it is a release.
 * @param releases - The releases under `versions/`.
 * @returns The module text.
 * @throws Error when every release is a snapshot.
 */
export const javaReleasesSource = (releases: readonly DumpedRelease[]): string => {
    const { newest, older } = spoken(releases);
    const kept = [newest, ...older];
    return `${registryHeader}
/**
 * The Java Edition releases this server speaks, newest first.
 *
 * Each release's number and packet ids are generated from its server jar under \`versions/<release>/\`.
 * A snapshot's number has bit 30 set, so it would sort above every release; snapshots are left out.
 */
${kept
    .map(
        ({ version }) =>
            `import { PACKETS as PACKETS_${identifierOf(version)} } from './${version}/packets';\nimport { RELEASE as RELEASE_${identifierOf(version)} } from './${version}/release';\n`
    )
    .join('')}import type { JavaProtocol } from './javaRelease';
${older
    .map(
        ({ version }) =>
            `\n/** Java Edition ${version} and its packet ids. */\nconst JAVA_${identifierOf(version)}: JavaProtocol = { ...RELEASE_${identifierOf(version)}, packets: PACKETS_${identifierOf(version)} };\n`
    )
    .join('')}
/** The newest release this server speaks, which a server list ping advertises. */
export const NEWEST_JAVA_RELEASE: JavaProtocol = { ...RELEASE_${identifierOf(newest.version)}, packets: PACKETS_${identifierOf(newest.version)} };

/** Every release this server speaks, newest first. */
export const JAVA_RELEASES: readonly JavaProtocol[] = [${['NEWEST_JAVA_RELEASE', ...older.map(({ version }) => `JAVA_${identifierOf(version)}`)].join(', ')}];
`;
};

/**
 * The source of `newest.ts`: the newest spoken release's data under the names each release's own
 * modules give it, so the code that configures and shows a Java client names no release and moves
 * to the next one with the dump.
 * @param releases - The releases under `versions/`.
 * @returns The module text.
 * @throws Error when every release is a snapshot.
 */
export const newestSource = (releases: readonly DumpedRelease[]): string => {
    const { version } = spoken(releases).newest;
    const constants = STATIC_REGISTRIES.map((name) => STATIC_REGISTRY_CONSTANTS[name].constant);
    return `${registryHeader}
/**
 * The data of Java Edition ${version}, the newest release this server speaks, which a Java client is
 * configured and shown with.
 */
import { BLOCK_STATES as RELEASE_BLOCK_STATES } from './${version}/blockStates';
import { CONFIGURATION as RELEASE_CONFIGURATION } from './${version}/configuration';
import { ENGLISH as RELEASE_ENGLISH } from './${version}/lang';
import type { PACKETS } from './${version}/packets';
import { ${constants.map((constant) => `${constant} as RELEASE_${constant}`).join(', ')} } from './${version}/registries';

/** Every block state's id, by block and property values. */
export const BLOCK_STATES = RELEASE_BLOCK_STATES;

/** What vanilla sends a client in the configuration phase. */
export const CONFIGURATION = RELEASE_CONFIGURATION;

/** The English of the keys the server sends or prints itself. */
export const ENGLISH = RELEASE_ENGLISH;
${STATIC_REGISTRIES.map((name) => {
    const { constant, doc } = STATIC_REGISTRY_CONSTANTS[name];
    return `\n/** ${doc} */\nexport const ${constant} = RELEASE_${constant};\n`;
}).join('')}
/** The packet ids, by phase, direction and Mojang's name, which the packet paths are checked against. */
export type NewestPackets = typeof PACKETS;
`;
};
