/** The TypeScript `dump:java-protocol` writes, kept apart from the run so it can be tested. */
import { isRecord } from '../isRecord.ts';

/** Packet ids by phase, then direction, then Mojang's packet name. */
export type PacketTable = Record<string, Record<string, Record<string, number>>>;

const NAMESPACE = 'minecraft:';

const header = (release: string): string =>
    `// Generated by \`pnpm --filter @jsprismarine/bedrock-data run dump:java-protocol --java ${release}\`. Do not edit.\n`;

/**
 * The source of `release.ts`.
 * @param release - The release id.
 * @param protocolVersion - The jar's `protocol_version`.
 * @returns The module text.
 */
export const releaseSource = (release: string, protocolVersion: number): string =>
    `${header(release)}
import type { JavaRelease } from '../javaRelease';

/** Java Edition ${release}, as its server jar's \`version.json\` names it. */
export const RELEASE: JavaRelease = { minecraftVersion: '${release}', protocolVersion: ${protocolVersion} };
`;

/**
 * The source of `packets.ts`, with each phase, direction and packet in name order and the
 * namespace taken off the names, which are all Mojang's.
 * @param release - The release id.
 * @param table - The data generator's ids.
 * @returns The module text.
 * @throws Error for a packet outside the `minecraft` namespace, which would mean the report changed shape.
 */
export const packetTableSource = (release: string, table: PacketTable): string => {
    const sorted = <T>(record: Record<string, T>): [string, T][] =>
        Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    // Prettier's style here: no comma after the last entry of an object.
    const block = (indent: string, entries: string[]): string => entries.join(',\n') + '\n' + indent;
    const phases = sorted(table).map(
        ([phase, directions]) =>
            `    ${phase}: {\n${block(
                '    ',
                sorted(directions).map(
                    ([direction, packets]) =>
                        `        ${direction}: {\n${block(
                            '        ',
                            sorted(packets).map(([name, id]) => {
                                if (!name.startsWith(NAMESPACE)) {
                                    throw new Error(`packet ${name} is outside the minecraft namespace`);
                                }
                                const key = name.slice(NAMESPACE.length);
                                // `debug/block_value` and its kin are no identifiers, so they are quoted.
                                return `            ${/^[a-z_][a-z0-9_]*$/.test(key) ? key : `'${key}'`}: ${id}`;
                            })
                        )}}`
                )
            )}}`
    );
    return `${header(release)}
/** Java Edition ${release}'s packet ids by phase, direction and Mojang's packet name, from the data generator's packets report. */
export const PACKETS = {
${phases.join(',\n')}
} as const;
`;
};

/** One block of the data generator's `reports/blocks.json`. */
export interface ReportBlock {
    readonly properties?: Readonly<Record<string, readonly string[]>>;
    readonly states: readonly { readonly id: number; readonly properties?: Readonly<Record<string, string>> }[];
}

/** One block's states: its name, the id of its first state, and its properties in the order that numbers them. */
export type BlockStateRow = [name: string, firstId: number, properties: [name: string, values: string[]][]];

/**
 * Each block's states as a row, from which every state id follows: the first id, plus the state's
 * value indices read as a mixed-radix number over the properties in the row's order.
 *
 * The report lists a block's properties in another order than the one that numbers its states, so
 * the order is read off the ids: a property's stride is how far one step of its value moves the id.
 * `JavaBlockStates.test.ts` in the protocol package checks every reported state against the rows.
 * @param report - The data generator's blocks report.
 * @returns The rows, in id order.
 * @throws Error when a block has no state one step along a property, so the report changed shape.
 */
export const blockStateRows = (report: Readonly<Record<string, ReportBlock>>): BlockStateRow[] => {
    const rows: BlockStateRow[] = [];
    for (const [name, block] of Object.entries(report)) {
        const properties = Object.entries(block.properties ?? {});
        const first = block.states.reduce((lowest, state) => (state.id < lowest.id ? state : lowest));
        const stride = (property: string, values: readonly string[]): number => {
            const from = first.properties?.[property] ?? '';
            const next = { ...first.properties, [property]: values[(values.indexOf(from) + 1) % values.length]! };
            const stepped = block.states.find((state) =>
                Object.entries(next).every(([key, value]) => state.properties?.[key] === value)
            );
            if (stepped === undefined) throw new Error(`${name} has no state with ${property}=${next[property]}`);
            return Math.abs(stepped.id - first.id);
        };
        const ordered = properties
            .map(([property, values]) => ({ property, values: [...values], stride: stride(property, values) }))
            .sort((a, b) => b.stride - a.stride)
            .map(({ property, values }): [string, string[]] => [property, values]);
        const row: BlockStateRow = [name, first.id, ordered];
        rows.push(row);
    }
    return rows.sort((a, b) => a[1] - b[1]);
};

/**
 * The JSON of the rows, one block a line.
 * @param rows - The rows.
 * @returns The file text.
 */
export const blockStatesSource = (rows: readonly BlockStateRow[]): string =>
    `[\n${rows.map((row) => `    ${JSON.stringify(row)}`).join(',\n')}\n]\n`;

/** The static registries `registries.json` holds, by the report's name. */
export const STATIC_REGISTRIES = ['minecraft:entity_type', 'minecraft:item'] as const;

/**
 * The JSON of the static registries: each one's entry names in network id order, under its name
 * without the namespace.
 * @param report - The data generator's registries report.
 * @param names - The registries to write.
 * @returns The file text.
 * @throws Error for a registry the report lacks, or ids that are not 0 to the entry count.
 */
export const staticRegistriesSource = (report: unknown, names: readonly string[]): string => {
    const out: string[] = [];
    for (const name of names) {
        // Extracted game data in the report's shape; a missing entry list throws below.
        const registry = (report as Record<string, { entries?: Record<string, { protocol_id: number }> }>)[name];
        if (registry?.entries === undefined) throw new Error(`the registries report has no ${name}`);
        const entries = Object.entries(registry.entries).sort(([, a], [, b]) => a.protocol_id - b.protocol_id);
        entries.forEach(([entry, { protocol_id }], index) => {
            if (protocol_id !== index) throw new Error(`${name} ${entry} has id ${protocol_id}, not ${index}`);
        });
        out.push(`    "${name.replace(/^minecraft:/, '')}": ${JSON.stringify(entries.map(([entry]) => entry))}`);
    }
    return `{\n${out.join(',\n')}\n}\n`;
};

/**
 * The English strings the server itself sends or prints, by key prefix: why a client is
 * disconnected, who joined and left, and how a player died. The console prints them, and a client
 * that has no translation of a key is shown them.
 */
export const LANG_PREFIXES = ['multiplayer.disconnect.', 'multiplayer.player.', 'death.'] as const;

/**
 * The JSON of the English strings under the given prefixes, in key order.
 * @param lang - The release's `en_us.json`.
 * @param prefixes - The prefixes of the keys to keep.
 * @returns The file text.
 * @throws Error for a file that is not an object of strings.
 */
export const langSource = (lang: unknown, prefixes: readonly string[]): string => {
    if (!isRecord(lang)) throw new Error('en_us.json is not an object of strings');
    const kept: Record<string, string> = {};
    for (const key of Object.keys(lang).sort()) {
        if (!prefixes.some((prefix) => key.startsWith(prefix))) continue;
        const text = lang[key];
        if (typeof text !== 'string') throw new Error(`en_us.json gives ${key} no string`);
        kept[key] = text;
    }
    return `${JSON.stringify(kept, null, 4)}\n`;
};
