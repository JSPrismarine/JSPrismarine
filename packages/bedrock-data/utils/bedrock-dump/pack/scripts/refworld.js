/**
 * Makes a server with no player on it generate the reference region, then says when it is done.
 *
 * A Bedrock server generates a chunk when something loads it, and on a fresh world with nobody
 * connected nothing does. A ticking area is the handle on that: `createTickingArea` resolves
 * "when all the chunks in the area are loaded and ticking", which is also when the generator has
 * finished with them. The region is wider than one area may cover, so it comes in tiles. The
 * Script API also limits total ticking chunks per pack, so completed areas must be released when
 * the next tile would exceed that budget — and the release has to be given a tick to land, or the
 * area that triggered it never resolves and the pass hangs for its whole timeout.
 *
 * The chunks reach disk when the server shuts down cleanly, so the job sends `stop` after the
 * last marker rather than killing the process. Nothing here reads the world back; that is
 * `utils/bedrock-dump/world.ts`, against the saved database.
 *
 * `region.js` beside this file is generated by `utils/bedrock-dump/pack.ts` from `region.ts`, so
 * the region this script loads and the region the reader hashes cannot drift apart.
 */

import { system, world } from '@minecraft/server';

import { DIMENSION, TILES } from './region.js';

/** Shared with `utils/bedrock-dump/protocol.ts`, which parses what this writes. */
const PREFIX = 'DUMP ';

let rows = 0;
let errors = 0;

/** Resolves on the next tick, which is when a ticking area removal has taken effect. */
const nextTick = () => new Promise((resolve) => system.runTimeout(resolve, 1));

const emit = (table, value) => {
    rows++;
    console.warn(`${PREFIX}${table} ${JSON.stringify(value)}`);
};

world.afterEvents.worldLoad.subscribe(async () => {
    const dimension = world.getDimension(DIMENSION);
    const manager = world.tickingAreaManager;
    console.warn(
        `${PREFIX}begin ${JSON.stringify({
            seed: String(world.seed),
            dimension: DIMENSION,
            tiles: TILES.length,
            maxTickingChunks: manager?.maxChunkCount ?? null
        })}`
    );

    for (const tile of TILES) {
        const started = Date.now();
        const area = {
            dimension,
            from: { x: tile.from[0], y: 0, z: tile.from[1] },
            to: { x: tile.to[0], y: 0, z: tile.to[1] }
        };
        try {
            if (!manager.hasCapacity(area)) {
                // Releasing and re-creating in one tick never resolves, so let the removal land.
                manager.removeAllTickingAreas();
                await nextTick();
            }
            if (!manager.hasCapacity(area)) {
                throw new Error(
                    `The ticking area manager's ${manager.maxChunkCount}-chunk budget cannot fit ` +
                        `tile ${tile.id} (${tile.chunks} chunks).`
                );
            }
            await manager.createTickingArea(tile.id, area);
            emit('reference-tiles', {
                id: tile.id,
                chunks: tile.chunks,
                from: tile.from,
                to: tile.to,
                millis: Date.now() - started
            });
        } catch (error) {
            errors++;
            emit('errors', {
                table: 'reference-tiles',
                id: tile.id,
                message: String(error && error.message ? error.message : error)
            });
        }
    }

    // One tick after the last area resolved, so the tick the chunks finished on has ended.
    system.runTimeout(() => {
        console.warn(`${PREFIX}end ${JSON.stringify({ rows, errors })}`);
    }, 1);
});
