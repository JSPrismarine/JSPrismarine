/** The files `dump:java-textures` writes, kept apart from the run so they can be tested. */
import type { TextureMatches } from './match.ts';

/**
 * `vanillaTextures.json`: each matched Bedrock texture with its Java textures, and the unmatched
 * ones, in path order. The run formats it with Prettier, as every checked-in file is.
 */
export const textureTableSource = ({ matched, unmatched }: TextureMatches): string =>
    `${JSON.stringify({ matched: Object.fromEntries(matched), unmatched }, null, 4)}\n`;

/**
 * `vanillaTextures.ts`, which types the table and names the sources it was generated from.
 * @param release - The Java release whose client jar the Java textures came from.
 * @param samples - The `bedrock-samples` tag the Bedrock textures came from.
 */
export const textureTableModuleSource = (release: string, samples: string): string =>
    `// Generated by \`pnpm --filter @jsprismarine/bedrock-data run dump:java-textures --java ${release}\`. Do not edit.

import table from './vanillaTextures.json' with { type: 'json' };

/** The Java release whose client jar the Java textures come from. */
export const VANILLA_TEXTURES_JAVA_RELEASE = '${release}';

/** The \`bedrock-samples\` tag whose vanilla resource pack the Bedrock textures come from. */
export const VANILLA_TEXTURES_BEDROCK_SAMPLES = '${samples}';

/**
 * The Java textures each vanilla Bedrock color texture is, by its path from the pack root without
 * an extension, such as \`textures/blocks/stone\` to \`["block/stone"]\`: the one of the same name
 * and size, or else the ones with the same pixels that no other Bedrock texture is named for.
 */
export const VANILLA_TEXTURES: ReadonlyMap<string, readonly string[]> = new Map(Object.entries(table.matched));

/** The vanilla Bedrock color textures no Java texture is, such as Bedrock-only blocks and differing layouts. */
export const UNMATCHED_VANILLA_TEXTURES: ReadonlySet<string> = new Set(table.unmatched);
`;
